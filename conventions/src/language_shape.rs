//! A language that a scaffold generated stays small: one module file, an SDK, and the kit's work.
//! 脚手架生成的语言保持小：一个模块文件、一个 SDK，其余是 kit 的工作。
//!
//! The kit exists so a new language writes its spelling and its carrier hooks, not a second parser
//! or renderer. Without a gate, the first urgent fix inside such a language grows a local `read` or
//! `render` again, and the next language copies it. The marker in the module's docs is what makes the
//! rule testable: only files a scaffold generated are held to it, so the two hand-written languages
//! (which predate the kit) are not retroactively failed.
//! kit 的存在是为了让一门新语言只写自己的拼法与载体钩子，而不是第二份解析器或渲染器。没有门禁，这种语言
//! 里的第一次紧急修复就会重新长出本地 `read`/`render`，下一门语言再抄一遍。模块文档里的标记让规则可测：
//! 只有脚手架生成的文件受它约束，因此两门早于 kit 的手写语言不会被追溯判红。

use std::fs;
use std::path::Path;

use crate::relative;

/// The doc line a scaffold writes; only modules that opt into the kit are judged.
/// 脚手架写下的文档行；只有声明使用 kit 的模块才被判定。
pub const MARKER: &str = "Generated by `xirang lang new`";

/// The doc line a hand-written language writes to opt into the same shape rule.
/// 手写语言声明遵守同一形状规则所写的文档行。
pub const KIT_MARKER: &str = "Uses the language kit";

/// The most Rust files one scaffolded language may keep (module plus two helpers).
/// 一门脚手架语言最多保留的 Rust 文件数（模块加两个助手）。
pub const MAX_FILES: usize = 3;

/// Languages written before this rule, with the file count they may keep while they migrate.
/// 本规则之前手写的语言，以及迁移期间允许保留的文件数。
///
/// A **generated** language never gets an entry: the scaffold writes exactly the shape, so an entry
/// there would only weaken the contract the scaffold states. A hand-written language that opts in
/// records its debt here, with the number it has today; the entry must shrink as pieces move into
/// the kit, and a stale entry (above the real count) is not a failure, just a licence it no longer
/// needs.
/// **生成**的语言永远没有条目：脚手架写的就是这个形状，条目只会削弱脚手架声明的契约。选择加入的手写
/// 语言在这里记录它的债务与今天的文件数；随着各块搬进 kit，这个数应当变小，而过期的条目（大于真实数）
/// 不是失败，只是一份它不再需要的许可。
pub const BASELINE: &[(&str, usize)] = &[("cpp", 8), ("c", 4)];

/// Text a scaffolded language must not carry: the kit owns these implementations. A language
/// still writes its own declaration parser and renderer — that is its job — but it asks the kit for
/// the capability table, the definition walk and the two name rules.
/// 脚手架语言不得携带的文本：这些实现归 kit 所有。语言仍写自己的声明解析器与渲染器——那是它的职责——
/// 但能力表、定义遍历与两条命名规则要向 kit 要。
pub const OWNED_BY_KIT: &[&str] = &["LanguageCapabilities {", "fn walk_nodes("];

/// Whether a file carries one kit-owned implementation.
/// 一个文件是否携带某项 kit 拥有的实现。
///
/// The capability literal is flagged only where it is **constructed**: a function returning
/// `&'static LanguageCapabilities` has the same words and is the required delegation, not a second
/// implementation. A same-named local helper with different meaning (`fn module_of` computing a
/// Python module from a destination) is not a duplicate of the kit's own and is not judged.
/// 能力字面量只在**构造**处被标记：返回 `&'static LanguageCapabilities` 的函数有同样的词，却是必需的委托，
/// 不是第二份实现。同名的本地助手若含义不同（`fn module_of` 从目标路径算 Python 模块），并不与 kit 的
/// 同名实现重复，也不被判定。
fn carries(text: &str, owned: &str) -> bool {
    text.lines().any(|line| {
        if !line.contains(owned) {
            return false;
        }
        !(owned.ends_with('{') && line.contains("->"))
    })
}

/// One scaffolded language that outgrew its shape.
/// 一门超出自己形状的脚手架语言。
#[derive(Debug, PartialEq, Eq, PartialOrd, Ord)]
pub struct Finding {
    /// The language directory, relative to the workspace root.
    /// 语言目录，以工作区根为基准。
    pub directory: String,
    /// What is wrong.
    /// 哪里不对。
    pub reason: String,
}

/// Every scaffolded language that broke the shape rule.
/// 每个破坏形状规则的脚手架语言。
pub fn findings(root: &Path) -> Vec<Finding> {
    let languages = root.join("multilang/src/languages");
    let mut found = Vec::new();
    let Ok(entries) = fs::read_dir(&languages) else {
        return found;
    };
    let mut directories: Vec<_> = entries.flatten().map(|entry| entry.path()).collect();
    directories.sort();
    for directory in directories {
        if !directory.is_dir() {
            continue;
        }
        let Some(name) = directory.file_name().and_then(|name| name.to_str()) else {
            continue;
        };
        let module = directory.join(format!("{name}.rs"));
        let Ok(source) = fs::read_to_string(&module) else {
            continue;
        };
        if !source.contains(MARKER) && !source.contains(KIT_MARKER) {
            continue;
        }
        let directory_name = relative(root, &directory);
        let files: Vec<String> = fs::read_dir(&directory)
            .map(|entries| {
                entries
                    .flatten()
                    .filter_map(|entry| entry.file_name().to_str().map(str::to_owned))
                    .filter(|file| file.ends_with(".rs"))
                    .filter(|file| !file.ends_with("_tests.rs"))
                    .collect()
            })
            .unwrap_or_default();
        let generated = source.contains(MARKER);
        let allowed = if generated {
            MAX_FILES
        } else {
            BASELINE
                .iter()
                .find(|(language, _)| *language == name)
                .map_or(MAX_FILES, |(_, allowed)| *allowed)
        };
        if files.len() > allowed {
            found.push(Finding {
                directory: directory_name.clone(),
                reason: format!(
                    "{} Rust files (at most {allowed}): a scaffolded language keeps its carrier \
                     hooks here and asks the kit for the rest",
                    files.len()
                ),
            });
        }
        for (name, text) in files.iter().filter_map(|file| {
            fs::read_to_string(directory.join(file))
                .ok()
                .map(|text| (file.as_str(), text))
        }) {
            for owned in OWNED_BY_KIT {
                if carries(&text, owned) {
                    found.push(Finding {
                        directory: directory_name.clone(),
                        reason: format!(
                            "`{name}` carries `{owned}`, which the kit owns; a scaffolded language \
                             supplies spelling and hooks, not a second implementation"
                        ),
                    });
                }
            }
        }
        if !root.join("multilang/sdk").join(name).is_dir() {
            found.push(Finding {
                directory: directory_name,
                reason: format!("no SDK directory `multilang/sdk/{name}/`"),
            });
        }
    }
    found
}

