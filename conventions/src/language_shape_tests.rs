//! Pins for the scaffolded-language shape gate.
//! 脚手架语言形状门禁的钉子。

use std::fs;

use super::{KIT_MARKER, MAX_FILES, findings};

fn synthetic(label: &str) -> std::path::PathBuf {
    let root = std::env::temp_dir().join(format!(
        "xirang-language-shape-{label}-{}",
        std::process::id()
    ));
    let _ = fs::remove_dir_all(&root);
    fs::create_dir_all(root.join("multilang/src/languages")).expect("fixture languages");
    root
}

fn language(root: &std::path::Path, name: &str, module: &str, extra: &[(&str, &str)]) {
    let directory = root.join("multilang/src/languages").join(name);
    fs::create_dir_all(&directory).expect("fixture language");
    fs::write(directory.join(format!("{name}.rs")), module).expect("fixture module");
    for (file, text) in extra {
        fs::write(directory.join(file), text).expect("fixture file");
    }
    fs::create_dir_all(root.join("multilang/sdk").join(name)).expect("fixture sdk");
}

const GENERATED: &str = "//! Generated by `xirang lang new`; fill the hooks.\n//! 由 `xirang lang new` 生成；填充钩子。\n";

/// A scaffolded language with one module, two helpers and an SDK is accepted.
/// 一个模块、两个助手与一个 SDK 的脚手架语言通过。
#[test]
fn a_small_scaffolded_language_passes() {
    let root = synthetic("small");
    language(
        &root,
        "toy",
        GENERATED,
        &[
            ("render.rs", "fn render_one() {}\n"),
            ("plan.rs", "fn plan_one() {}\n"),
        ],
    );
    assert_eq!(findings(&root), vec![], "a small language is the shape");
    let _ = fs::remove_dir_all(root);
}

/// Too many Rust files, a reimplemented kit function, or a missing SDK each fail by name.
/// Rust 文件太多、重实现 kit 函数、或缺少 SDK，都会按名失败。
#[test]
fn each_way_out_of_the_shape_is_named() {
    let root = synthetic("broken");
    let mut extra = Vec::new();
    for index in 0..=MAX_FILES {
        extra.push((format!("helper{index}.rs"), String::new()));
    }
    let extra: Vec<(&str, &str)> = extra
        .iter()
        .map(|(file, text)| (file.as_str(), text.as_str()))
        .collect();
    language(&root, "wide", GENERATED, &extra);
    language(
        &root,
        "deep",
        GENERATED,
        &[(
            "parse.rs",
            "const TABLE: LanguageCapabilities { language: todo!() };\n",
        )],
    );
    let missing = root.join("multilang/src/languages/alone");
    fs::create_dir_all(&missing).expect("fixture language");
    fs::write(missing.join("alone.rs"), GENERATED).expect("fixture module");
    let found = findings(&root);
    assert!(
        found
            .iter()
            .any(|finding| finding.reason.contains("Rust files")),
        "the wire of files is named: {found:#?}"
    );
    assert!(
        found
            .iter()
            .any(|finding| finding.reason.contains("LanguageCapabilities {")),
        "the reimplementation is named: {found:#?}"
    );
    assert!(
        found
            .iter()
            .any(|finding| finding.reason.contains("no SDK directory")),
        "the missing SDK is named: {found:#?}"
    );
    let _ = fs::remove_dir_all(root);
}

/// A language that opts in with the kit marker is judged; one with neither marker is not.
/// 声明使用 kit 的语言受判定；两个标记都没有的语言不受判定。
#[test]
fn opting_in_marks_a_hand_written_language_too() {
    let root = synthetic("legacy");
    language(
        &root,
        "old",
        "//! A hand-written language.\n//! 手写语言。\n",
        &[(
            "parse.rs",
            "const TABLE: LanguageCapabilities { language: todo!() };\n",
        )],
    );
    assert_eq!(
        findings(&root),
        vec![],
        "a language that did not opt in predates the rule"
    );
    let opted_in = root.join("multilang/src/languages/old/old.rs");
    fs::write(&opted_in, format!("//! {KIT_MARKER}\n")).expect("opt in");
    let found = findings(&root);
    assert!(
        found
            .iter()
            .any(|finding| finding.reason.contains("LanguageCapabilities {")),
        "an opted-in language is judged by the same rule, even when it was hand-written: {found:#?}"
    );
    let _ = fs::remove_dir_all(root);
}

/// The shipped checkout itself respects the shape rule: this is the half that makes the gate a gate.
/// 出厂检出本身遵守形状规则：这一半才让门禁成为门禁。
#[test]
fn the_shipped_tree_respects_the_shape() {
    let found = findings(&crate::workspace_root());
    assert!(
        found.is_empty(),
        "the shipped languages that opted into the kit keep the shape: {found:#?}"
    );
}

/// A scaffolded language that re-implements the kit's walker is refused by name.
/// 重实现 kit 遍历器的脚手架语言按名拒绝。
#[test]
fn a_second_walker_is_named() {
    let root = synthetic("walker");
    language(
        &root,
        "toy",
        GENERATED,
        &[(
            "walk.rs",
            "pub fn walk_nodes(stream: &[u8]) -> Vec<u8> { stream.to_vec() }\n",
        )],
    );
    let found = findings(&root);
    assert!(
        found
            .iter()
            .any(|finding| finding.reason.contains("fn walk_nodes(")),
        "the second walker is named: {found:#?}"
    );
    let _ = fs::remove_dir_all(root);
}

/// A baseline entry licences a hand-written language's current count, never a generated one's.
/// 基线条目许可手写语言当前的文件数，绝不许可生成语言。
#[test]
fn the_baseline_covers_hand_written_languages_only() {
    let root = synthetic("baseline");
    let mut extra = Vec::new();
    // The module itself plus seven helpers is the eight files the baseline licences.
    // 模块本身加七个助手，就是基线条目许可的那八个文件。
    for index in 0..7 {
        extra.push((format!("helper{index}.rs"), String::new()));
    }
    let extra: Vec<(&str, &str)> = extra
        .iter()
        .map(|(file, text)| (file.as_str(), text.as_str()))
        .collect();
    language(&root, "cpp", KIT_MARKER, &extra);
    assert_eq!(
        findings(&root),
        vec![],
        "the baseline licence covers the hand-written language's current count"
    );
    language(&root, "generated", GENERATED, &extra);
    let found = findings(&root);
    assert!(
        found
            .iter()
            .any(|finding| finding.directory.ends_with("/generated")
                && finding.reason.contains("Rust files")),
        "a generated language gets no baseline: {found:#?}"
    );
    let _ = fs::remove_dir_all(root);
}
