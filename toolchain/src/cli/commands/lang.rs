//! `xirang lang new <id>`: scaffold one language module the way the kit expects it.
//! `xirang lang new <id>`：按 kit 期望的样子脚手架一门语言模块。
//!
//! The scaffold writes **two** files — the module and an SDK stub — and prints the registration
//! lines it cannot write safely (the crate manifests and the registry entry). The module is marked
//! so `conventions::language_shape` can hold it to the shape: one module, no second parser or
//! renderer, an SDK beside it.
//! 脚手架写**两个**文件——模块与 SDK 桩——并打印它无法安全写入的注册行（crate 清单与注册表条目）。模块带
//! 标记，因此 `conventions::language_shape` 能把它约束在形状里：一个模块、没有第二份解析器或渲染器、旁边有 SDK。

use std::io::Write;
use std::path::{Path, PathBuf};

/// The first doc line of every scaffolded module; the shape gate keys on it.
/// 每个脚手架模块的首行文档；形状门禁以它为键。
pub const MARKER: &str = "Generated by `xirang lang new`";

/// One file a scaffold plans to write, as a package-relative path and its text.
/// 脚手架计划写入的一个文件，按包内相对路径与文本。
pub struct Planned {
    /// Path relative to the checkout root.
    /// 相对检出根的路径。
    pub path: PathBuf,
    /// The file's text.
    /// 文件文本。
    pub text: String,
}

/// The language's Rust type name (`toy_box` → `ToyBox`).
/// 语言的 Rust 类型名（`toy_box` → `ToyBox`）。
fn type_name(id: &str) -> String {
    id.split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut characters = part.chars();
            characters
                .next()
                .map(|first| first.to_ascii_uppercase().to_string() + characters.as_str())
                .unwrap_or_default()
        })
        .collect()
}

/// Validate a language id and return the type name, or refuse by name.
/// 校验语言 id 并返回类型名，否则按名拒绝。
fn checked(id: &str, extension: &str) -> Result<String, String> {
    let good = id
        .chars()
        .next()
        .is_some_and(|first| first.is_ascii_lowercase())
        && id.chars().all(|character| {
            character.is_ascii_lowercase() || character.is_ascii_digit() || character == '_'
        });
    if !good {
        return Err(format!(
            "`{id}` is not a language id: use lowercase letters, digits and `_`, starting with a letter"
        ));
    }
    if [
        "kit", "naming", "rust", "cpp", "c", "python", "zig", "js", "ts", "go", "java", "csharp",
    ]
    .contains(&id)
    {
        return Err(format!("`{id}` is a language this build already carries"));
    }
    if extension.is_empty()
        || extension.chars().any(|character| {
            !character.is_ascii_alphanumeric() && character != '_' && character != '.'
        })
    {
        return Err(format!("`{extension}` is not a file extension"));
    }
    Ok(type_name(id))
}

/// The files one scaffolded language consists of.
/// 一门脚手架语言由哪些文件组成。
pub fn plan(id: &str, extension: &str) -> Result<Vec<Planned>, String> {
    let name = checked(id, extension)?;
    let module = format!(
        r#"//! {MARKER}: the spelling and hooks of `{id}`, filled in from this skeleton.
//! {MARKER}：`{id}` 的拼法与钩子，从这个骨架填起。
//!
//! Everything shared lives in `crate::languages::kit`: the adapter orchestration, the field table
//! (whose spellings and value styles are below), and the declaration walk. This module owns only
//! what `{id}` itself decides — how one declaration is written and read back.
//! 一切共享的东西住在 `crate::languages::kit`：适配器编排、字段表（拼法与取值风格在下面）与声明遍历。
//! 本模块只拥有 `{id}` 自己决定的东西——一条声明怎么写、怎么读回。

use std::sync::OnceLock;

use xirang_kernel::authoring::{{AuthoringOperation, FaceAuthoringPlan, FaceAuthoringRequest,
    LanguageCapabilities, RegistrationField}};

use crate::languages::kit::adapter::{{AdapterSpec, capabilities as kit_capabilities}};
use crate::languages::kit::grammar::{{DeclaredFace, FaceGrammar}};
use crate::registration::{{FaceReadBack, LanguageAdapter}};

/// The `{id}` language implementation.
/// `{id}` 语言实现。
pub struct {name};

/// What this language tells the shared adapter about itself.
/// 这门语言告诉共享适配器的东西。
const SPEC: AdapterSpec = AdapterSpec {{
    language: "{id}",
    extensions: &["{extension}"],
    fields: RegistrationField::ALL,
    operations: &[AuthoringOperation::Create, AuthoringOperation::Modify],
    carrying: "a `{id}` declaration",
}};

/// The fields a `{id}` declaration carries, with their spellings and value styles.
/// `{id}` 声明携带的字段，及其拼法与取值风格。
pub const GRAMMAR: FaceGrammar = FaceGrammar {{ fields: &[] }};

static CAPABILITIES: OnceLock<LanguageCapabilities> = OnceLock::new();

fn capabilities() -> &'static LanguageCapabilities {{
    kit_capabilities(&CAPABILITIES, &SPEC)
}}

/// Read one `{id}` declaration into the shared payload.
/// 把一条 `{id}` 声明读成共享载荷。
fn declared(_source: &str) -> Result<DeclaredFace, String> {{
    Err("`{id}`: the scaffold's declaration reader is not implemented yet".to_owned())
}}

/// Render one created declaration.
/// 渲染一条新建声明。
fn create(_request: &FaceAuthoringRequest) -> Result<FaceAuthoringPlan, String> {{
    Err("`{id}`: the scaffold's create is not implemented yet".to_owned())
}}

/// Render one modified declaration.
/// 渲染一条修改声明。
fn modify(_request: &FaceAuthoringRequest) -> Result<FaceAuthoringPlan, String> {{
    Err("`{id}`: the scaffold's modify is not implemented yet".to_owned())
}}

impl LanguageAdapter for {name} {{
    fn capabilities(&self) -> &'static LanguageCapabilities {{
        capabilities()
    }}

    fn read(&self, source: &str) -> Result<FaceReadBack, String> {{
        crate::languages::kit::adapter::read_back(declared, source)
    }}

    fn plan(&self, request: &FaceAuthoringRequest) -> Result<FaceAuthoringPlan, String> {{
        crate::languages::kit::adapter::plan(&SPEC, request, create, modify)
    }}
}}
"#
    );
    let sdk = format!(
        "# `{id}` SDK\n\n# `{id}` SDK\n\nThis directory is the SDK the `{id}` implementation ships for its own sources: the\ninclude directory a `{id}` file adds to see the generated face constants, and any helper the\nlanguage needs to declare a face in place.\n\n本目录是 `{id}` 实现为自己的源码发布的 SDK：`{id}` 文件看到生成的面常量所需的包含目录，以及该语言在\n原地声明一个面所需的任何助手。\n"
    );
    Ok(vec![
        Planned {
            path: PathBuf::from(format!("multilang/src/languages/{id}/{id}.rs")),
            text: module,
        },
        Planned {
            path: PathBuf::from(format!("multilang/sdk/{id}/README.md")),
            text: sdk,
        },
    ])
}

/// The registration lines a human has to add; the scaffold prints them instead of guessing at
/// manifest edits.
/// 人需要添加的注册行；脚手架打印它们，而不是去猜清单编辑。
pub fn registration(id: &str) -> Vec<String> {
    let name = type_name(id);
    vec![
        format!(
            "multilang/src/languages.rs: #[cfg(feature = \"lang-{id}\")] #[path = \"languages/{id}/{id}.rs\"] pub mod {id};"
        ),
        format!(
            "multilang/src/lib.rs: #[cfg(feature = \"lang-{id}\")] pub use languages::{id}::{name};"
        ),
        format!("multilang/Cargo.toml: lang-{id} = [\"semantics\"]"),
        format!("toolchain/Cargo.toml: lang-{id} = [\"xirang-multilang/lang-{id}\"]"),
        format!(
            "multilang/src/registration.rs: #[cfg(feature = \"lang-{id}\")] adapters.push(&crate::languages::{id}::{name});"
        ),
    ]
}

/// Write the plan under one checkout, refusing any existing target before writing anything.
/// 在某个检出下写入计划；先拒绝任何已存在的目标，再动手。
pub fn write_files(checkout: &Path, id: &str, extension: &str) -> Result<Vec<PathBuf>, String> {
    let planned = plan(id, extension)?;
    for planned in &planned {
        let target = checkout.join(&planned.path);
        if target.exists() {
            return Err(format!(
                "`{}` already exists; the scaffold writes only into an empty place",
                planned.path.display()
            ));
        }
    }
    let mut written = Vec::new();
    for planned in planned {
        let target = checkout.join(&planned.path);
        if let Some(parent) = target.parent() {
            std::fs::create_dir_all(parent)
                .map_err(|error| format!("{}: {error}", parent.display()))?;
        }
        std::fs::write(&target, planned.text)
            .map_err(|error| format!("{}: {error}", target.display()))?;
        written.push(planned.path);
    }
    Ok(written)
}

/// The anchors a registration edit relies on, with the text each file gains.
/// 注册编辑依赖的锚点，以及每个文件要加上的文本。
///
/// All anchors are checked before any file is written: a checkout that does not have them is refused
/// with the file named, rather than half-registered.
/// 所有锚点都在写入任何文件之前检查：没有这些锚点的检出会被按文件点名拒绝，而不是注册一半。
pub fn registration_edits(id: &str) -> Result<Vec<(&'static str, &'static str, String)>, String> {
    let name = type_name(id);
    Ok(vec![
        (
            "multilang/src/languages.rs",
            "pub mod rust;",
            format!(
                "pub mod rust;\n\n#[cfg(feature = \"lang-{id}\")]\n#[path = \"languages/{id}/{id}.rs\"]\npub mod {id};"
            ),
        ),
        (
            "multilang/src/lib.rs",
            "pub mod languages;",
            format!(
                "pub mod languages;\n\n#[cfg(feature = \"lang-{id}\")]\npub use languages::{id}::{name};"
            ),
        ),
        (
            "multilang/Cargo.toml",
            "lang-python = [\"semantics\"]",
            format!("lang-python = [\"semantics\"]\nlang-{id} = [\"semantics\"]"),
        ),
        (
            "toolchain/Cargo.toml",
            "lang-python = [\"xirang-multilang/lang-python\"]",
            format!(
                "lang-python = [\"xirang-multilang/lang-python\"]\nlang-{id} = [\"xirang-multilang/lang-{id}\"]"
            ),
        ),
        (
            "multilang/src/registration.rs",
            "            adapters.push(&PythonLanguage);",
            format!(
                "            adapters.push(&PythonLanguage);\n        }}\n        #[cfg(feature = \"lang-{id}\")]\n        {{\n            adapters.push(&crate::languages::{id}::{name});"
            ),
        ),
    ])
}

/// Apply the registration edits, checking every anchor and every target before writing anything.
/// 应用注册编辑：先检查每个锚点与目标，再写入任何东西。
pub fn register(checkout: &Path, id: &str) -> Result<Vec<&'static str>, String> {
    let edits = registration_edits(id)?;
    let mut sources = Vec::new();
    for (path, anchor, replacement) in &edits {
        let target = checkout.join(path);
        let source = std::fs::read_to_string(&target)
            .map_err(|error| format!("{}: {error}", target.display()))?;
        if !source.contains(anchor) {
            return Err(format!(
                "{}: the anchor `{anchor}` is not there; register `{id}` by hand",
                target.display()
            ));
        }
        if source.contains(&format!("lang-{id}")) || source.contains(&format!("::{id}::")) {
            return Err(format!(
                "{} already mentions `{id}`; the scaffold does not register twice",
                target.display()
            ));
        }
        let updated = source.replace(anchor, replacement);
        sources.push((target, updated));
    }
    let mut written = Vec::new();
    for (target, updated) in sources {
        std::fs::write(&target, updated)
            .map_err(|error| format!("{}: {error}", target.display()))?;
        written.push(target);
    }
    let _ = written;
    Ok(edits.iter().map(|(path, _, _)| *path).collect())
}

/// `xirang lang new <id> [--extension <ext>] [--checkout <path>] [--apply]`.
/// `xirang lang new <id> [--extension <ext>] [--checkout <path>] [--apply]`。
pub fn lang(args: &mut impl Iterator<Item = String>, out: &mut dyn Write) -> Result<(), String> {
    let Some(action) = args.next() else {
        return Err(
            "usage: xirang lang new <id> [--extension <ext>] [--checkout <path>] [--apply]"
                .to_owned(),
        );
    };
    if action != "new" {
        return Err(format!(
            "`lang {action}` is not a command; the only one is `lang new`"
        ));
    }
    let mut id = None;
    let mut extension = None;
    let mut checkout = None;
    let mut apply = false;
    let mut register_edits_requested = false;
    while let Some(argument) = args.next() {
        match argument.as_str() {
            "--apply" => apply = true,
            "--register" => register_edits_requested = true,
            "--extension" => {
                extension = Some(
                    args.next()
                        .ok_or_else(|| "`--extension` needs a value".to_owned())?,
                );
            }
            "--checkout" => {
                checkout = Some(PathBuf::from(
                    args.next()
                        .ok_or_else(|| "`--checkout` needs a path".to_owned())?,
                ));
            }
            other if other.starts_with("--") => {
                return Err(format!("`{other}` is not an option of `xirang lang new`"));
            }
            other => id = Some(other.to_owned()),
        }
    }
    let id = id.ok_or_else(|| "`xirang lang new` needs a language id".to_owned())?;
    let extension = extension.unwrap_or_else(|| id.clone());
    let planned = plan(&id, &extension)?;
    for planned in &planned {
        writeln!(out, "would write {}", planned.path.display())
            .map_err(|error| error.to_string())?;
    }
    for line in registration(&id) {
        writeln!(out, "register: {line}").map_err(|error| error.to_string())?;
    }
    if apply {
        let checkout = checkout.ok_or_else(|| {
            "`--apply` needs `--checkout <path>`: the scaffold writes into a checkout, never into the current directory by guess"
                .to_owned()
        })?;
        for path in write_files(&checkout, &id, &extension)? {
            writeln!(out, "wrote {}", path.display()).map_err(|error| error.to_string())?;
        }
        if register_edits_requested {
            for path in register(&checkout, &id)? {
                writeln!(out, "registered in {path}").map_err(|error| error.to_string())?;
            }
        }
        writeln!(
            out,
            "next: add the registration lines above, then `cargo test -p xirang-multilang --features lang-{id}`"
        )
        .map_err(|error| error.to_string())?;
    } else {
        writeln!(
            out,
            "dry run: add `--apply --checkout <path>` to write these files"
        )
        .map_err(|error| error.to_string())?;
    }
    Ok(())
}

