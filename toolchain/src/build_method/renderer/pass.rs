//! The top-level pass that assembles the generated lib.
//! 组装生成 lib 的顶层流程。
//!
//! `render_lib` writes the fixed preamble, the object aliases, the module tree,
//! its real module mounts, and the build-time static plan in the order rustc requires;
//! the recursion itself and the child emitters live in the sibling modules.
//! `render_lib` 按 rustc 要求的顺序写出固定前言、对象别名、模块树、其 真实模块挂载
//! 与构建期静态计划；递归本身与各子发射器位于同级模块。

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use super::aliases::{registry_path, render_object_aliases};
use super::owners::{
    bare_module, emitted_grafts, face_module, graft_constructor, owned, registry_name_for,
    resolve_own_rule,
};
use super::tree::{ShapeRender, render_nodes};
use crate::build_method::diagnostics::BuildDiagnostics;
use crate::build_method::registry_syntax::GraftSyntax;
use crate::build_method::static_plan::StaticFaceRecord;
use crate::build_method::{Node, SourceScope};

// Each parameter is one concept this render consumes — the sources, the two diagnostic sets, the
// scope, the static plan, the graft cuts and the crate shape — and every caller passes all of them;
// grouping them into a struct would invent a type no caller wants to name.
// 每个参数都是本次渲染消费的一个概念——源码、两套诊断、作用域、静态计划、graft 切口与 crate 形状——而每个
// 调用方都要把它们全交过来；把它们装进一个结构体只会造出一个没有调用方愿意命名的类型。
#[cfg(test)]
#[allow(clippy::too_many_arguments)]
pub(crate) fn render_lib(
    src: &Path,
    nodes: &[Node],
    errors: &BuildDiagnostics,
    demo_errors: &BuildDiagnostics,
    scope: &SourceScope,
    static_faces: &[StaticFaceRecord],
    grafts: &[GraftSyntax],
    shape: ShapeRender<'_>,
    module_directory: &Path,
    module_files: &mut Vec<(String, String)>,
) -> String {
    render_lib_with_external(
        src,
        nodes,
        errors,
        demo_errors,
        scope,
        static_faces,
        grafts,
        shape,
        module_directory,
        module_files,
        &[],
        &[],
    )
}

/// `render_lib`, plus the faces a C++ build declared in its `xirang.faces` sections.
/// `render_lib`，外加 C++ 构建在 `xirang.faces` 段里声明的那些面。
///
/// The two halves are rendered together on purpose: they land in one
/// `BUILTIN_STATIC_FACES` table and one `registrations()` list, so a caller that
/// rendered them separately would have to merge what the runtime reads as one.
/// 两半故意一起渲染：它们进的是同一张 `BUILTIN_STATIC_FACES` 表与同一份 `registrations()`
/// 清单，分开渲染的调用方就得自己去合并运行期当作一张表读的东西。
/// One foreign face as the renderer needs it: identity, tree position, the name the tree shows, the
/// exports the compiler recorded, and the identifier the generated header names it by.
/// 渲染器需要的一个外语面：身份、树位置、树上的显示名、编译器记录的导出，以及生成头文件点名它用的标识符。
struct NativeFace {
    id: crate::build_method::registry_identity::NodeId,
    parent: crate::build_method::registry_identity::NodeId,
    owns_registry: bool,
    name: String,
    source: String,
    exports: Vec<String>,
    ident: String,
    /// The record's version-2 fields. They are empty for a version-1 record, which is exactly the
    /// standard registration default the tree then shows.
    /// 记录的版本 2 字段。版本 1 记录里它们为空，而那正是树随后显示的标准注册默认值。
    registry_name: String,
    stable_name: String,
    provides: Vec<String>,
    requires: Vec<(String, String)>,
    preset: String,
    parts: String,
    params: String,
    handle: String,
    name_zh: String,
    name_en: String,
    summary_zh: String,
    summary_en: String,
    from_registry: String,
}

#[allow(clippy::too_many_arguments)]
pub(crate) fn render_lib_with_external(
    src: &Path,
    nodes: &[Node],
    errors: &BuildDiagnostics,
    demo_errors: &BuildDiagnostics,
    scope: &SourceScope,
    static_faces: &[StaticFaceRecord],
    grafts: &[GraftSyntax],
    shape: ShapeRender<'_>,
    module_directory: &Path,
    module_files: &mut Vec<(String, String)>,
    external: &[crate::build_method::external_face::ExternalFaceRecord],
    native: &[crate::build_method::declared_native::Resolved],
) -> String {
    let mut output = String::from(
        "// @generated by build.rs; do not edit.\n// 由 build.rs 生成，请勿手工修改。\n\n",
    );
    let registry = registry_path();
    // A facade compiles no faces: no vocabulary aliases, no modules, no IDE shadows. Everything it
    // carries is emitted below, rewritten to the crates that own each module (audit `M7`, §M7.33).
    // facade 不编译任何面：不发词表别名、不发模块、不发 真实模块挂载。它携带的一切都在下面发射，并改写成各自模块的
    // 属主 crate（审计 `M7`，§M7.33）。
    if !shape.facade {
        render_object_aliases(&mut output, src, nodes);
        render_nodes(
            &mut output,
            src,
            scope,
            nodes,
            shape,
            module_directory,
            module_files,
        );
    }
    output.push_str(&format!("\npub use {registry}::*;\n"));
    // One row per foreign face. Before the compiler has run (pass one) the declarations are the only
    // source of truth, so the tree still shows the face and the header still names it; after it has run
    // (pass two) the records carry what the compiler wrote — exports and the ownership flag — and the
    // declarations keep the one thing a record cannot carry: the identifier a child names.
    // 每个外语面一行。编译器还没跑时（第一遍）声明是唯一的事实来源，因此树照样显示那个面、头文件照样点名它；
    // 跑完之后（第二遍）记录带着编译器写下的东西——导出与属主标志——而声明保留记录带不了的那一样：子面要
    // 点名的标识符。
    let rows: Vec<NativeFace> = if external.is_empty() {
        native
            .iter()
            .map(|face| NativeFace {
                id: face.id,
                parent: face.parent,
                owns_registry: face.owns_registry,
                name: face.name.clone(),
                source: face.source.clone(),
                exports: Vec::new(),
                ident: face.ident.clone(),
                registry_name: String::new(),
                stable_name: String::new(),
                provides: Vec::new(),
                requires: Vec::new(),
                preset: String::new(),
                parts: String::new(),
                params: String::new(),
                handle: String::new(),
                name_zh: String::new(),
                name_en: String::new(),
                summary_zh: String::new(),
                summary_en: String::new(),
                from_registry: String::new(),
            })
            .collect()
    } else {
        external
            .iter()
            .map(|face| NativeFace {
                id: face.id,
                parent: face.parent,
                owns_registry: face.owns_registry,
                name: face.name.clone(),
                source: face.source.clone(),
                exports: face.exports.clone(),
                ident: native
                    .iter()
                    .find(|native| native.id == face.id)
                    .map(|native| native.ident.clone())
                    .unwrap_or_default(),
                registry_name: face.registry_name.clone(),
                stable_name: face.stable_name.clone(),
                provides: face.provides.clone(),
                requires: face.requires.clone(),
                preset: face.preset.clone(),
                parts: face.parts.clone(),
                params: face.params.clone(),
                handle: face.handle.clone(),
                name_zh: face.name_zh.clone(),
                name_en: face.name_en.clone(),
                summary_zh: face.summary_zh.clone(),
                summary_en: face.summary_en.clone(),
                from_registry: face.getting_from_other_registry.clone(),
            })
            .collect()
    };
    output.push_str(&format!(
        "\n#[doc(hidden)]\npub static BUILTIN_STATIC_FACES: &[{registry}::StaticFace] = &[\n",
    ));
    for face in static_faces {
        writeln!(output, "    {registry}::StaticFace::new({registry}::NodeId::from_raw({:?}), {registry}::NodeId::from_raw({:?}), {}),", face.id.into_bytes(), face.parent.into_bytes(), face.owns_registry).unwrap();
    }
    // A face declared in C++ has no Rust constant to read: the build read its record out of the
    // object file, so the table entry is written here from that record. The identity was assigned by
    // `external_face::records` from the source spelling — the same rule `#[soil]` uses — so the two
    // kinds of face land in one identity space rather than in two tables.
    // C++ 声明的面没有可读的 Rust 常量：构建是从目标文件里读出记录的，因此表项在这里按记录写出。
    // 身份由 `external_face::records` 按源码拼写算出——与 `#[soil]` 同一条规则——因此两类面进的是
    // 同一个身份空间，而不是两张表。
    for face in &rows {
        writeln!(output, "    {registry}::StaticFace::new({registry}::NodeId::from_raw({:?}), {registry}::NodeId::from_raw({:?}), {}),", face.id.into_bytes(), face.parent.into_bytes(), face.owns_registry).unwrap();
    }
    output.push_str("];\n");
    // A face written as a `Registration` literal (H/A2e) has no module-level `RegistrationInfo`: its
    // declaration is a value the author wrote, and only the build knows the identity, the type names and
    // the source location. So the tree assembles the snapshot it needs — once per face, here — and the
    // consumers below read that one constant. The macros keep emitting their own, because in them a
    // preset and a parts type are **types**, not names.
    // 写成 `Registration` 字面量的面（H/A2e）没有模块级 `RegistrationInfo`：它的声明是作者写下的值，而身份、
    // 类型名与源码位置只有构建知道。因此生成树在这里**每个面拼一次**它需要的快照，下面的消费者读同一个常量。
    // 宏那两种拼法继续自己发射——在它们那里，preset 与 parts 是**类型**，不是名字。
    let mut assembled = BTreeMap::new();
    for (index, face) in static_faces.iter().enumerate() {
        if !face.written_as_literal {
            continue;
        }
        let name = format!("__XIRANG_ASSEMBLED_{index}");
        // Bound before the `writeln!` because the template names it inline (`{rule}`): the rule is an
        // expression, not a `{:?}` value, so it cannot ride the positional argument list.
        // 在 `writeln!` 之前绑定，因为模板以内联名引用它（`{rule}`）：规则是一个**表达式**而不是 `{:?}` 值，
        // 因此不能跟着位置参数走。
        // Spelled for the crate that emits it: a facade carries the host's modules under their owner's
        // name, so a bare `crate::<module>::registry_rule::…` resolves there only after `owned` rewrites
        // it — measured, this is exactly the line that failed to resolve in the facade's tree.
        // 按**发射它的那个 crate**拼写：facade 把宿主的模块挂在属主名下，因此裸 `crate::<模块>::registry_rule::…`
        // 只有在 `owned` 改写之后才解析得到——实测：facade 的树里报错的就是这一行。
        let rule = owned(
            &shape,
            &resolve_own_rule(&face.module, face.owns_registry, &registry),
        );
        writeln!(
            output,
            "const {name}: {registry}::RegistrationInfo = {registry}::RegistrationInfo::assemble_face::<{}::{}>(\n    {registry}::FaceInputs {{\n        namespace: crate::XIRANG_NAMESPACE,\n        id: {registry}::NodeId::from_raw({:?}),\n        kind: {:?},\n        registry_name: {:?},\n        registry_rule: {rule},\n        preset: {:?},\n        parts: {:?},\n        params: {:?},\n        handle: {:?},\n        source: {registry}::SourceLocation {{ file: {:?}, line: 0, column: 0, function: {:?} }},\n        handle_traits: &[],\n        part_traits: &[],\n    }},\n    {}::{}::REGISTRATION,\n);\n",
            owned(&shape, &face.module),
            face.kind,
            face.id.into_bytes(),
            face.kind,
            registry_name_for(face),
            face.preset,
            face.parts,
            face.kind,
            face.kind,
            face.source,
            face.kind,
            owned(&shape, &face.module),
            face.kind,
        )
        .unwrap();
        assembled.insert(face.id, name);
    }
    // An external face declares no Rust types, so its snapshot is assembled from the record alone:
    // both type parameters are the empty pair, and every field the record does not carry keeps its
    // default. The record carries one spelling of the name, which is shown in both languages until a
    // slice carries the second one.
    // 外部面不声明 Rust 类型，因此它的快照只从记录拼出：两个类型参数都取空对，记录不携带的字段保持
    // 默认。版本 2 的记录携带的字段逐项填进去；版本 1 的记录只有名字与导出，其余显示为默认。
    for (index, face) in rows.iter().enumerate() {
        let exports = face
            .exports
            .iter()
            .map(|name| format!("{name:?}"))
            .collect::<Vec<_>>()
            .join(", ");
        let provides = face
            .provides
            .iter()
            .map(|name| format!("{name:?}"))
            .collect::<Vec<_>>()
            .join(", ");
        let requires = face
            .requires
            .iter()
            .map(|(capability, provider)| {
                format!(
                    "{registry}::RequirementSpec {{ capability: {capability:?}, provider: {provider:?} }}"
                )
            })
            .collect::<Vec<_>>()
            .join(", ");
        // The tree's path segment is the name the declaration gives itself (`.named(…)`), not the
        // file it happens to live in. The file stem is the **physical** name: a move that renames
        // the file must not rename the object, because the logical path is what identity, grafts and
        // third-party references name. A Rust face's segment is its module because for Rust the
        // module *is* the declared name; a foreign declaration has no module, so its `.named` value
        // is the only author-owned name there is.
        // 树上的路径段是声明给自己起的名字（`.named(…)`），而不是它恰好所在的文件。文件 stem 是**物理**名：
        // 改文件名的搬动不得改掉对象名，因为逻辑路径才是身份、嫁接与第三方引用所点名的那一个。Rust 面的段是
        // 它的模块，因为对 Rust 而言模块**就是**声明的名字；外语声明没有模块，因此 `.named` 的值是唯一由作者
        // 拥有的名字。
        let registry_name = if face.registry_name.is_empty() {
            face.name.clone()
        } else {
            face.registry_name.clone()
        };
        // A version-1 record carries one spelling of the name; a version-2 record can carry the two
        // halves separately. An empty half falls back to the kind, which is what that half showed
        // before the field existed — never to an empty display name.
        // 版本 1 记录只带一种名字拼写；版本 2 记录可以分别携带两半。为空的一半回退到 kind——也就是这个
        // 字段存在之前它显示的东西——而不是变成空显示名。
        let name_zh = if face.name_zh.is_empty() {
            &face.name
        } else {
            &face.name_zh
        };
        let name_en = if face.name_en.is_empty() {
            &face.name
        } else {
            &face.name_en
        };
        let stable_name = if face.stable_name.is_empty() {
            "None".to_owned()
        } else {
            format!("Some({:?})", face.stable_name)
        };
        let from_registry = if face.from_registry.is_empty() {
            "None".to_owned()
        } else {
            format!("Some({:?})", face.from_registry)
        };
        writeln!(
            output,
            "const __XIRANG_EXTERNAL_{index}: {registry}::RegistrationInfo = {registry}::RegistrationInfo::assemble::<{registry}::NoPreset, {registry}::NoParts>(\n    {registry}::FaceInputs {{\n        namespace: crate::XIRANG_NAMESPACE,\n        id: {registry}::NodeId::from_raw({id:?}),\n        kind: {name:?},\n        registry_name: {registry_name:?},\n        registry_rule: {registry}::RegistrationRule::ANY,\n        preset: {preset:?},\n        parts: {parts:?},\n        params: {params:?},\n        handle: {handle:?},\n        source: {registry}::SourceLocation {{ file: {source:?}, line: 0, column: 0, function: {name:?} }},\n        handle_traits: &[],\n        part_traits: &[],\n    }},\n    {registry}::Registration {{\n        parent: {registry}::NodeId::from_raw({parent:?}),\n        stable_name: {stable_name},\n        name: {registry}::LocalizedText {{ zh: {name_zh:?}, en: {name_en:?} }},\n        summary: {registry}::LocalizedText {{ zh: {summary_zh:?}, en: {summary_en:?} }},\n        exports: &[{exports}],\n        needs_registry: {owns},\n        registry_name: {registry_name:?},\n        getting_from_other_registry: {from_registry},\n        provides: &[{provides}],\n        requires: &[{requires}],\n        ..{registry}::Registration::DEFAULT\n    }},\n);\n",
            id = face.id.into_bytes(),
            name = face.name,
            registry_name = registry_name,
            preset = face.preset,
            parts = face.parts,
            params = face.params,
            handle = face.handle,
            name_zh = name_zh,
            name_en = name_en,
            summary_zh = face.summary_zh,
            summary_en = face.summary_en,
            stable_name = stable_name,
            from_registry = from_registry,
            source = face.source,
            parent = face.parent.into_bytes(),
            owns = face.owns_registry,
        )
        .unwrap();
    }
    // A Rust child whose parent is a foreign face needs the same constant the C++ side gets: the
    // identity has to be nameable from Rust, and hand-writing sixteen bytes is the maintenance this
    // interface exists to remove. The module is generated from the same rows the tree is built from,
    // so it cannot drift from it.
    // Rust 子面的父是外语面时，它需要 C++ 侧拿到的同一个常量：身份必须能从 Rust 点名，而手写十六个字节
    // 正是这套接口要消灭的维护。这个模块由树的那批行生成，因此不会与树漂移。
    if rows.iter().any(|face| !face.ident.is_empty()) {
        output.push_str(
            "\n/// Identities of the faces this project declares in a foreign language.\n\
             /// 本项目在别的语言里声明的面的身份。\n\
             #[doc(hidden)]\n#[allow(non_upper_case_globals)]\npub mod xirang_external {\n",
        );
        for face in &rows {
            if face.ident.is_empty() {
                continue;
            }
            writeln!(
                output,
                "    /// One face declared in a foreign language, addressed the way every other parent is:\n    /// `crate::xirang_external::<ident>::NODE_ID`.\n    /// 一个声明在别的语言里的面，拼法与其他父面一致：`crate::xirang_external::<ident>::NODE_ID`。\n    #[allow(non_snake_case)]\n    pub mod {} {{\n        /// The identity the generated header also carries.\n        /// 生成头同样携带的身份。\n        pub const NODE_ID: {registry}::NodeId = {registry}::NodeId::from_raw({:?});\n    }}",
                face.ident,
                face.id.into_bytes()
            )
            .unwrap();
        }
        output.push_str("}\n");
    }
    let modules = static_faces
        .iter()
        .map(|face| (face.id, face.module.as_str()))
        .collect::<BTreeMap<_, _>>();
    output.push_str("\n// Registration rules are consumed by const evaluation only.\n// 注册规则只参与常量求值，不进入发布态数据。\n");
    for face in static_faces {
        let rule = super::owners::parent_rule(&shape, &modules, &assembled, face.parent, &registry);
        writeln!(
            output,
            "const _: () = {registry}::assert_static_registration({}, {});",
            owned(&shape, &rule),
            assembled
                .get(&face.id)
                .cloned()
                .unwrap_or_else(|| format!("{}::REGISTRATION", owned(&shape, &face.module)))
        )
        .unwrap();
    }
    output.push_str(&format!(
        "\n#[doc(hidden)]\npub static BUILTIN_GRAFT_CUTS: &[{registry}::StaticGraftCut] = &[\n",
    ));
    let mut cut_contracts = String::new();
    // The attribution happens once, in `emitted_grafts`, and the same list is what the build writes to
    // `graft_plan.tsv` — an audit text that described a different table than this literal is what made
    // two readers conclude the release shape carried every cut everywhere (audit `M7`, §M7.55).
    // 归属只判一次，在 `emitted_grafts` 里，而构建写进 `graft_plan.tsv` 的就是同一份清单——审计文本若描述
    // 的是另一张表，正是让两位读者得出"发布形状到处都是全量切口"的原因（审计 `M7`，§M7.55）。
    let emitted = emitted_grafts(static_faces, grafts, shape.facade);
    for graft in &emitted {
        writeln!(
            output,
            "    {},",
            graft_constructor(&shape, graft, &registry)
        )
        .unwrap();
        // A typed cut names both endpoints as expressions, so the compiler can
        // also check the one thing a selector cannot: that the replacement's
        // parts construct exactly what the cut object's preset expects. The
        // assertion is an item, so it leaves this array literal for the block
        // below; a cut written as a logical path or a selector contributes
        // nothing, because the build step has no module to name for it and
        // inventing one would assert about a guess.
        // 类型化切口把两端写成表达式，因此编译器还能检查选择器检查不了的那件事：替换面的
        // parts 构造出来的东西，正好是切口对象的 preset 所期望的。断言是一个条目，因此它
        // 离开这个数组字面量、写到下面的块里；写成逻辑路径或选择器的切口什么也不贡献——
        // 构建步骤没有可命名的模块，编一个出来等于对猜测做断言。
        if let Some(expressions) = &graft.expressions
            && let (Some(cut), Some(graft_module)) = (
                face_module(&expressions.cut),
                face_module(&expressions.graft),
            )
        {
            // A face written as a `Registration` literal (H/A2e) has no `__Preset`/`__Parts`: those are
            // type aliases the declaration macros emit. Its type-like half lives on its `FaceContract`
            // impl, and the face's name is the kind — which the record carries, so the tree can name the
            // type instead of an alias nobody wrote. The macro spellings keep the aliases, byte for byte.
            // 写成 `Registration` 字面量的面（H/A2e）没有 `__Preset`/`__Parts`：那是声明宏发射的类型别名。
            // 它类型类的那一半住在 `FaceContract` 实现上，而那个面的名字就是 kind——记录里带着它，因此生成树
            // 可以点名那个**类型**，而不是一个没人写过的别名。宏那两种拼法保留别名，逐字不变。
            let type_like = |module: &str, associated: &str| -> String {
                // The two keys are spelled differently on purpose: a graft expression names a module as
                // the source spells it (`crate::control::object::slider`), while the record keeps the
                // module's own path (`control::object::slider`). Compare the part that identifies the
                // module.
                // 两个键的写法**有意**不同：切口表达式按源码的写法命名模块（`crate::control::object::slider`），
                // 而记录里存的是模块自己的路径（`control::object::slider`）。比的是能认出那个模块的那一段。
                match static_faces.iter().find(|face| {
                    bare_module(&face.module) == bare_module(module) && face.written_as_literal
                }) {
                    // The assertion already opens one `<`, so this names the type without another pair.
                    // 断言自己已经开了一个 `<`，因此这里点名那个类型时不再套一对。
                    Some(face) => format!(
                        "<{}::{} as {registry}::FaceContract>::{associated}",
                        owned(&shape, module),
                        face.kind
                    ),
                    None => format!("{}::__{associated}", owned(&shape, module)),
                }
            };
            writeln!(
                cut_contracts,
                "const _: () = {registry}::assert_contract::<{}, {}>();",
                type_like(cut, "Preset"),
                type_like(graft_module, "Parts")
            )
            .unwrap();
        }
    }
    let mut face_identities = String::new();
    // A face's own `NODE_ID` must be the one this build baked: the two are computed by different code
    // (the build walks the tree, the face hashes the path it was compiled from), so a partitioned
    // crate or a missing remap makes them disagree — silently, until this assertion exists.
    // 一个面自己的 `NODE_ID` 必须就是这个构建烤进去的那个：两者由不同的代码算出（构建走一遍树，面散列它被编译时
    // 的路径），因此分区 crate 或漏掉的 remap 会让它们不一致——在这条断言存在之前，那是静默的。
    for face in static_faces.iter().filter(|_| !shape.facade) {
        // The identity assertion belongs to the crate that **compiles** the face: the ghost has it, and
        // in the facade it would name a module the facade does not have (audit `M7`, §M7.33).
        // 身份断言属于**编译**该面的那个 crate：幽灵有它，而在 facade 里它只会点名一个 facade 没有的模块
        // （审计 `M7`，§M7.33）。
        // Both spellings carry a module-level `NODE_ID`, and the two sides come from **different code**: the
        // face's own constant is what that module compiled, while the id here is what this build derived by
        // walking the tree (namespace, package-relative source, kind). Comparing them is therefore a real
        // cross-check, and it is the only thing that catches a partitioned crate or a missing remap.
        // 两种拼法都带模块级 `NODE_ID`，而两侧来自**不同的代码**：面自己的常量是那个模块编译出来的，而这里的
        // id 是本构建走过树（命名空间、包内相对路径、kind）算出来的。比较两者才是一次真正的交叉核对，也是唯一
        // 能抓到分区 crate 或漏掉 remap 的东西。
        //
        // Compatibility policy for the literal spelling: it must declare `pub const NODE_ID` — the writer bakes
        // it into the generated region, so every face this tool ever wrote has it. A hand-written literal face
        // without that constant now **fails to compile here** (naming the module) instead of passing on an
        // identity check that compared a value with itself. Write such a face with `#[soil]`, which emits the
        // constant, or add it by hand.
        // 字面量拼法的兼容策略：它必须声明 `pub const NODE_ID`——写者会把它烘进生成区域，因此本工具写过的每个面
        // 都带着它。手写的字面量面若没有这个常量，现在会**在这里编译失败**（点名那个模块），而不是在一次"自己
        // 与自己比较"的身份检查上通过。这样的面请用 `#[soil]` 书写（由它发射常量），或手工补上。
        writeln!(
            face_identities,
            "const _: () = {registry}::assert_static_identity(crate::{module}::NODE_ID, {registry}::NodeId::from_raw({:?}));",
            face.id.into_bytes(),
            module = face.module
        )
        .unwrap();
    }
    output.push_str("];\n\n");
    output.push_str(&cut_contracts);
    output.push_str(&face_identities);
    // The host may have `#![warn(missing_docs)]` on, and it cannot edit this
    // generated file — so the raw static stays hidden plumbing the way
    // `BUILTIN_STATIC_FACES`/`BUILTIN_GRAFT_CUTS` do, while the two functions a
    // host actually calls carry the docs.
    // 宿主可能开着 `#![warn(missing_docs)]`，而它无法编辑这份生成文件——因此裸静态量像
    // `BUILTIN_STATIC_FACES`/`BUILTIN_GRAFT_CUTS` 一样保持为隐藏管道，而宿主真正调用的两个
    // 函数带上文档。
    output.push_str(&format!(
        "#[doc(hidden)]\npub static BUILTIN_STATIC_PLAN: {registry}::StaticPlan = {registry}::StaticPlan::with_grafts(BUILTIN_STATIC_FACES, BUILTIN_GRAFT_CUTS);\n\n"
    ));
    output.push_str(&format!(
        "/// The release-time static plan this build produced: the enabled faces plus their graft cuts.\n\
         /// 本次构建产出的发布态静态计划：启用的注册面加上它们的 graft 切口。\n\
         pub const fn builtin_static_plan() -> &'static {registry}::StaticPlan {{ &BUILTIN_STATIC_PLAN }}\n"
    ));
    output.push_str(
        "\n/// Every registration this build enabled, in tree order, as owned snapshots.\n\
         /// 本次构建启用的每一条注册，按树序，以拥有型快照给出。\n\
         pub fn registrations() -> Vec<RegistrationInfo> {\n    vec![\n",
    );
    for face in static_faces {
        // This snapshot names modules too, so it goes through the same rewrite as every other
        // cross-crate reference: a facade that left these bare failed with `cannot find module or crate
        // panel` (measured, §M7.38).
        // 这段快照同样点名模块，因此和其他跨 crate 引用一样走同一条改写：facade 里留裸名就会
        // `cannot find module or crate panel`（实测，§M7.38）。
        writeln!(
            output,
            "        {},",
            assembled
                .get(&face.id)
                .cloned()
                .unwrap_or_else(|| format!("{}::REGISTRATION", owned(&shape, &face.module)))
        )
        .unwrap();
    }
    for index in 0..external.len() {
        writeln!(output, "        __XIRANG_EXTERNAL_{index},").unwrap();
    }
    output.push_str("    ]\n        .into_iter()\n        .collect()\n}\n");
    if !errors.is_empty() {
        output.push('\n');
        writeln!(
            output,
            "compile_error!({:?});",
            errors.render_build_diagnostics()
        )
        .unwrap();
    }
    if !demo_errors.is_empty() {
        output.push_str(&format!(
            "\n#[cfg(feature = {:?})]\n",
            crate::build_method::DEMO_ONLY_FEATURE
        ));
        writeln!(
            output,
            "compile_error!({:?});",
            demo_errors.render_build_diagnostics()
        )
        .unwrap();
    }
    output
}

