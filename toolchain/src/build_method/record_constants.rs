//! The constants file a record-file language's declarations name their parents through.
//! 记录文件语言声明点名父级所用的常量文件。
//!
//! The record producer cannot compute a parent's identity: the identity is the build's (namespace,
//! source, name) hash, and the producer runs before the build has read the record. So the build
//! writes the identities it knows — the root and every Rust/declared face — into a file in that
//! language's own syntax, and the declaration names a constant from it. The user then builds the
//! package once, and every declaration that names a generated constant compiles.
//! 记录生产者算不出父身份：身份是构建的 (namespace, source, name) 散列，而生产者在构建读到记录之前运行。
//! 因此构建把它知道的身份——根与每个 Rust/声明面——按该语言自己的语法写进一个文件，声明从里面点名常量。
//! 用户于是构建一次包，每条点名生成常量的声明都能编译。

use std::path::{Path, PathBuf};

#[cfg(any(feature = "lang-go", feature = "lang-java", feature = "lang-csharp"))]
use xirang_kernel::identity::root_node_id;

/// What one package's `[record]` table asks the build to generate.
/// 一个包的 `[record]` 表让构建生成的东西。
#[derive(Clone, Debug)]
pub(crate) struct Request {
    /// The language whose syntax the constants file is written in.
    /// 常量文件用哪种语言的语法写。
    pub(crate) language: String,
    /// The package-relative constants file.
    /// 包内相对的常量文件。
    pub(crate) path: PathBuf,
}

/// Collect the identities the build knows from its two face lists and write the constants file.
/// 从构建的两份面清单收集它知道的身份，写出常量文件。
pub(crate) fn write_for_faces(
    request: &Request,
    package_root: &Path,
    namespace: &str,
    static_faces: &[super::static_plan::StaticFaceRecord],
    native: &[super::declared_native::Resolved],
) -> Result<(), String> {
    let mut identities: Vec<(String, [u8; 16])> = static_faces
        .iter()
        .map(|face| (face.module.clone(), face.id.into_bytes()))
        .collect();
    identities.extend(native.iter().map(|face| {
        (
            super::declared_native::module_of(&face.source),
            face.id.into_bytes(),
        )
    }));
    write(request, package_root, namespace, &identities)
}

/// Write the constants file for the faces this build knows.
/// 为本次构建知道的面写出常量文件。
pub(crate) fn write(
    request: &Request,
    package_root: &Path,
    namespace: &str,
    faces: &[(String, [u8; 16])],
) -> Result<(), String> {
    let target = package_root.join(&request.path);
    let text = match request.language.as_str() {
        "go" => render_go(&target, namespace, faces)?,
        "java" => render_java(&target, namespace, faces)?,
        "csharp" => render_csharp(&target, namespace, faces)?,
        other => {
            return Err(format!(
                "`[record] language` is `{other}`; this build generates constants files for `go`, \
                 `java` and `csharp`"
            ));
        }
    };
    if let Some(directory) = target.parent() {
        std::fs::create_dir_all(directory)
            .map_err(|error| format!("cannot create {}: {error}", directory.display()))?;
    }
    std::fs::write(&target, text)
        .map_err(|error| format!("cannot write {}: {error}", target.display()))
}

/// The Go constants file: the root plus one constant per face module.
/// Go 常量文件：根加上每个面模块一条常量。
#[cfg(feature = "lang-go")]
fn render_go(
    target: &Path,
    namespace: &str,
    faces: &[(String, [u8; 16])],
) -> Result<String, String> {
    let package = crate::build_method::record_constants::go_package(target)?;
    let mut entries: Vec<(String, [u8; 16])> = faces.to_vec();
    entries.sort_by(|left, right| left.0.cmp(&right.0));
    for pair in entries.windows(2) {
        if pair[0].0 == pair[1].0 {
            return Err(format!(
                "two faces share the module `{}`; a Go constant names one face per module, so the \
                 build cannot write both",
                pair[0].0
            ));
        }
    }
    let mut text = String::from("// Code generated by the build; do not edit.\n");
    text.push_str(&format!("package {package}\n\n"));
    text.push_str(&format!(
        "const rootNodeID = \"{}\"\n",
        hex(root_node_id(namespace).into_bytes())
    ));
    for (module, id) in &entries {
        if module.is_empty() {
            return Err("a face has an empty module; a Go constant needs a module path".to_owned());
        }
        text.push_str(&format!(
            "\n// {module}\nconst {} = \"{}\"\n",
            xirang_multilang::languages::go::names::face_constant(module),
            hex(*id)
        ));
    }
    Ok(text)
}

/// The Java constants class: the root plus one `static final String` per face module.
/// Java 常量类：根加上每个面模块一条 `static final String`。
#[cfg(feature = "lang-java")]
fn render_java(
    target: &Path,
    namespace: &str,
    faces: &[(String, [u8; 16])],
) -> Result<String, String> {
    if target.file_name().and_then(|name| name.to_str()) != Some("Faces.java") {
        return Err(format!(
            "the Java constants file must be `Faces.java` (the annotation imports `xirang.Faces`); \
             this path is {}",
            target.display()
        ));
    }
    let directory = target
        .parent()
        .and_then(|parent| parent.file_name())
        .and_then(|name| name.to_str())
        .filter(|name| *name == "xirang")
        .ok_or_else(|| {
            format!(
                "the Java constants file must live in a directory named `xirang` (its package is \
                 `xirang`, which the declarations import); this path is {}",
                target.display()
            )
        })?;
    let _ = directory;
    let mut entries: Vec<(String, [u8; 16])> = faces
        .iter()
        .map(|(module, id)| {
            (
                xirang_multilang::languages::java::names::face_constant(module),
                *id,
            )
        })
        .collect();
    entries.sort_by(|left, right| left.0.cmp(&right.0));
    for pair in entries.windows(2) {
        if pair[0].0 == pair[1].0 {
            return Err(format!(
                "two faces fold to the same Java constant `{}`; a class cannot hold two fields with \
                 one name",
                pair[0].0
            ));
        }
    }
    if entries.iter().any(|(name, _)| name == "ROOT_NODE_ID") {
        return Err(
            "a face module folds to `ROOT_NODE_ID`, which is the root's constant; rename the module"
                .to_owned(),
        );
    }
    let mut text = String::from("// Code generated by the build; do not edit.\n");
    text.push_str("package xirang;\n\n");
    text.push_str(
        "/**\n * The generated face identities this package names in annotations.\n */\n",
    );
    text.push_str("public final class Faces {\n");
    text.push_str(&format!(
        "    /** The registry root. */\n    public static final String ROOT_NODE_ID = \"{}\";\n",
        hex(root_node_id(namespace).into_bytes())
    ));
    for (name, id) in &entries {
        text.push_str(&format!(
            "\n    public static final String {name} = \"{}\";\n",
            hex(*id)
        ));
    }
    text.push_str("\n    private Faces() {}\n}\n");
    Ok(text)
}

