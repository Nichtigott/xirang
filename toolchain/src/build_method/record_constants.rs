/// The Go package a constants file belongs to: its directory's last segment, folded.
/// 常量文件所属的 Go 包：目录最后一段，折成合法标识符。
#[cfg(feature = "lang-go")]
fn go_package(target: &Path) -> Result<String, String> {
    let directory = target
        .parent()
        .and_then(|parent| parent.file_name())
        .and_then(|name| name.to_str())
        .filter(|name| !name.is_empty())
        .ok_or_else(|| {
            format!(
                "{} has no directory a Go package can be named after",
                target.display()
            )
        })?;
    Ok(xirang_multilang::languages::naming::go_segment(directory))
}

/// Sixteen bytes as lowercase hex, the spelling the record files and headers also use.
/// 十六字节的小写十六进制，记录文件与头文件同样使用的拼写。
#[cfg(any(feature = "lang-go", feature = "lang-java", feature = "lang-csharp"))]
fn hex(bytes: [u8; 16]) -> String {
    let mut text = String::with_capacity(32);
    for byte in bytes {
        text.push_str(&format!("{byte:02x}"));
    }
    text
}

