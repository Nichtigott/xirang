//! Pins for the constants file a record-file language names its parents through.
//! 记录文件语言用来点名父级的常量文件的钉子。

use super::*;

fn request(language: &str, path: &str) -> Request {
    Request {
        language: language.to_owned(),
        path: PathBuf::from(path),
    }
}

fn scratch(label: &str) -> PathBuf {
    let root = std::env::temp_dir().join(format!(
        "xirang-record-constants-{}-{label}",
        std::process::id()
    ));
    let _ = std::fs::remove_dir_all(&root);
    std::fs::create_dir_all(&root).expect("the scratch directory");
    root
}

/// A Go constants file carries the root and one named constant per face module.
/// Go 常量文件携带根与每个面模块一条具名常量。
#[cfg(feature = "lang-go")]
#[test]
fn a_go_constants_file_names_the_root_and_every_module() {
    let root = scratch("go-file");
    let faces = vec![
        ("panel".to_owned(), [0x11; 16]),
        ("shop::panel".to_owned(), [0x22; 16]),
    ];
    write(
        &request("go", "go/src/gauge/faces.go"),
        &root,
        "gauge",
        &faces,
    )
    .expect("the constants");
    let text = std::fs::read_to_string(root.join("go/src/gauge/faces.go")).expect("the file");
    assert!(
        text.starts_with("// Code generated by the build; do not edit.\n"),
        "{text}"
    );
    assert!(text.contains("package gauge\n"), "{text}");
    assert!(
        text.contains(&format!(
            "const rootNodeID = \"{}\"",
            hex(xirang_kernel::identity::root_node_id("gauge").into_bytes())
        )),
        "{text}"
    );
    assert!(text.contains("const xirangFacePanel = \"1111"), "{text}");
    assert!(
        text.contains("const xirangFaceShopPanel = \"2222"),
        "{text}"
    );
    let _ = std::fs::remove_dir_all(&root);
}

/// Two faces on one module cannot both be named by one Go constant.
/// 同一个模块上的两个面无法被一条 Go 常量同时命名。
#[cfg(feature = "lang-go")]
#[test]
fn two_faces_on_one_module_are_refused() {
    let root = scratch("go-duplicate");
    let faces = vec![("panel".to_owned(), [1; 16]), ("panel".to_owned(), [2; 16])];
    let why = write(
        &request("go", "go/src/gauge/faces.go"),
        &root,
        "gauge",
        &faces,
    )
    .expect_err("one constant cannot name two faces");
    assert!(why.contains("two faces share the module `panel`"), "{why}");
    let _ = std::fs::remove_dir_all(&root);
}

/// A language whose constants syntax this build does not carry is refused by name.
/// 本构建不携带其常量语法的语言按名拒绝。
#[test]
fn an_unknown_language_is_refused_by_name() {
    let root = scratch("unknown-language");
    let why = write(
        &request("kotlin", "kotlin/src/faces.kt"),
        &root,
        "gauge",
        &[],
    )
    .expect_err("no Kotlin constants writer yet");
    assert!(
        why.contains("generates constants files for `go`, `java` and `csharp`"),
        "{why}"
    );
    let _ = std::fs::remove_dir_all(&root);
}

/// A Java constants class names the root and every face module, in the `xirang` package.
/// Java 常量类在 `xirang` 包里命名根与每个面模块。
#[cfg(feature = "lang-java")]
#[test]
fn a_java_constants_class_names_the_root_and_every_module() {
    let root = scratch("java-file");
    let faces = vec![
        ("panel".to_owned(), [0x11; 16]),
        ("shop::panel".to_owned(), [0x22; 16]),
    ];
    write(
        &request("java", "java/gen/xirang/Faces.java"),
        &root,
        "gauge",
        &faces,
    )
    .expect("the constants");
    let text = std::fs::read_to_string(root.join("java/gen/xirang/Faces.java")).expect("the file");
    assert!(text.contains("package xirang;\n"), "{text}");
    assert!(text.contains("public final class Faces {"), "{text}");
    assert!(
        text.contains("public static final String ROOT_NODE_ID = \"d50d"),
        "{text}"
    );
    assert!(
        text.contains("public static final String PANEL_NODE_ID = \"1111"),
        "{text}"
    );
    assert!(
        text.contains("public static final String SHOP_PANEL_NODE_ID = \"2222"),
        "{text}"
    );
    let _ = std::fs::remove_dir_all(&root);
}

/// A Java constants file outside the `xirang` package is refused by name.
/// 不在 `xirang` 包里的 Java 常量文件按名拒绝。
#[cfg(feature = "lang-java")]
#[test]
fn a_java_constants_file_outside_the_package_is_refused() {
    let root = scratch("java-package");
    let why = write(&request("java", "java/gen/Faces.java"), &root, "gauge", &[])
        .expect_err("the class must live in its package directory");
    assert!(why.contains("directory named `xirang`"), "{why}");
    let _ = std::fs::remove_dir_all(&root);
}

/// Two modules folding to one Java constant are refused rather than silently colliding.
/// 折成同一个 Java 常量的两个模块按名拒绝，而不是静默冲突。
#[cfg(feature = "lang-java")]
#[test]
fn two_modules_folding_to_one_java_constant_are_refused() {
    let root = scratch("java-collision");
    let faces = vec![("a-b".to_owned(), [1; 16]), ("a_b".to_owned(), [2; 16])];
    let why = write(
        &request("java", "java/gen/xirang/Faces.java"),
        &root,
        "gauge",
        &faces,
    )
    .expect_err("one field name cannot name two faces");
    assert!(why.contains("same Java constant"), "{why}");
    let _ = std::fs::remove_dir_all(&root);
}

