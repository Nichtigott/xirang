//! Face source parsing boundary.
//! 注册面源码解析边界。

use std::collections::BTreeMap;
use std::path::Path;

use crate::run_method::authoring::context::authoring_namespace;
use crate::run_method::authoring::parse::{
    ParentMap, kind_from_source_path, module_name_from_path, module_source_from_node_path,
    parse_admission_expression, parse_flow_field, rule_syntax_for_source, source_path_from_file,
};
use crate::run_method::{NodeId, ParentSyntax, RuntimeCheckSpec, root_node_id};
use crate::source_cache::parse_face as parse_face_syntax;

use super::super::FaceManifest;

/// Parse one generated face through the authoring parser.
/// 通过 authoring 解析器读取一个生成注册面。
pub(crate) fn source(
    path: &Path,
    identity_prefix: &str,
    parents: Option<&ParentMap>,
) -> Result<FaceManifest, String> {
    parse_face_macro_impl(
        path,
        &std::fs::read_to_string(path).map_err(|error| error.to_string())?,
        identity_prefix,
        parents,
    )
}

/// Recover an authored face without a sidecar manifest or central index.
/// 不依赖旁置清单或中央索引，直接恢复文件里的注册面。
pub(crate) fn parse_face_macro_impl(
    path: &Path,
    text: &str,
    identity_prefix: &str,
    parents: Option<&ParentMap>,
) -> Result<FaceManifest, String> {
    let face = parse_face_syntax(text)
        .map_err(|error| format!("cannot parse {}: {error}", path.display()))?
        .ok_or_else(|| "this module was not generated by XiRang".to_owned())?;
    let mut values = BTreeMap::new();
    if let Some(collector) = face.field("collector") {
        values.insert("collector".to_owned(), collector);
    }
    let source = source_path_from_file(path);
    values.insert("source".to_owned(), source);
    // Which spelling the file uses (H/A2e). The renderer writes the same one back: a face an author
    // wrote as a `Registration` literal must not come back as a macro block.
    // 文件用的是哪种拼法（H/A2e）。渲染器写回同一种：作者写成 `Registration` 字面量的面，不该变回宏块。
    values.insert(
        "written_as_literal".to_owned(),
        face.is_struct_literal().to_string(),
    );
    values.insert("module".to_owned(), module_name_from_path(path));
    let declared_parent_registry = face
        .macro_name
        .strip_suffix("_object")
        // Studio must be able to open declarations written before hierarchy
        // macros existed. The build validator still rejects a newly generated
        // `control_object!` whose explicit parent is not `control`.
        // Studio 必须能打开层级宏出现前生成的声明；构建校验仍会拒绝新文件中
        // 与 control 父级不一致的 `control_object!`。
        .filter(|name| !matches!(*name, "control" | "external"));
    if let Some(parent_registry) = declared_parent_registry {
        values.insert(
            "parent_registry_name".to_owned(),
            parent_registry.to_owned(),
        );
    }

    for key in ["kind", "preset", "parts"] {
        if let Some(value) = face.path(key) {
            values.insert(key.to_owned(), value);
        }
    }
    // One key, so no loop: clippy's `single_element_loop` (new in 1.99) is right that a one-element
    // loop reads as if more keys were coming.
    // 只有一个键，因此不写循环：clippy 的 `single_element_loop`（1.99 新增）说得对——单元素循环读起来
    // 像后面还会有更多键。
    if let Some(value) = face.string("registry_rule_path") {
        values.insert("registry_rule_path".to_owned(), value);
    }
    if let Some(value) = face.boolean("needs_registry") {
        values.insert("needs_registry".to_owned(), value.to_string());
    }
    let kind = values.get("kind").cloned().unwrap_or_default();
    values.insert(
        "stable_name".to_owned(),
        face.string("stable_name").unwrap_or_default(),
    );
    values.insert(
        "name_zh".to_owned(),
        face.localized("name", "zh").unwrap_or_else(|| kind.clone()),
    );
    values.insert(
        "name_en".to_owned(),
        face.localized("name", "en").unwrap_or_else(|| kind.clone()),
    );
    values.insert(
        "summary_zh".to_owned(),
        face.localized("summary", "zh").unwrap_or_default(),
    );
    values.insert(
        "summary_en".to_owned(),
        face.localized("summary", "en").unwrap_or_default(),
    );
    values.insert(
        "exports".to_owned(),
        face.string_list("exports").unwrap_or_default().join(","),
    );
    values.insert(
        "parts".to_owned(),
        values
            .get("parts")
            .cloned()
            .filter(|value| !value.is_empty())
            .unwrap_or_else(|| "NoParts".to_owned()),
    );
    values.insert(
        "preset".to_owned(),
        values
            .get("preset")
            .cloned()
            .filter(|value| !value.is_empty())
            .unwrap_or_else(|| "NoPreset".to_owned()),
    );
    // There used to be a `handle` key here, seeded from `kind` because the
    // kernel's field word list does not carry `handle`, so the value was always
    // the kind. Nothing rendered it either (the template emits the kind), which
    // made it a field a caller could "edit" with no effect (audit `LG-38`). The
    // declaration macro derives the handle at the declaration site.
    // 这里过去有一个 `handle` 键，用 `kind` 播种，因为内核的字段词表里没有 `handle`，因此它的值
    // 永远是 kind。也没有任何东西渲染它（模板发射的是 kind），这让它成了一个调用方"能编辑"却毫无
    // 效果的字段（审计 `LG-38`）。句柄由声明宏在声明点派生。
    if let Some(plugin) = face.field(xirang_kernel::lexicon::FACE_FIELD_PLUGIN) {
        values.insert(xirang_kernel::lexicon::FACE_FIELD_PLUGIN.to_owned(), plugin);
    }
    values.insert(
        "getting_from_other_registry".to_owned(),
        face.option_string("getting_from_other_registry")
            .flatten()
            .unwrap_or_default(),
    );
    values.insert(
        "needs_registry".to_owned(),
        values
            .get("needs_registry")
            .cloned()
            .unwrap_or_else(|| "false".to_owned()),
    );
    values.insert(
        "admission".to_owned(),
        parse_admission_expression(face.field("admission").as_deref().unwrap_or(""))?,
    );
    // The view derives the labels from the paths when there are paths
    // (`FaceSyntax::string_list`), so this reader states nothing twice and cannot
    // disagree with the build-time contract check that reads the same view.
    // 有路径时视图会从路径推导标签（`FaceSyntax::string_list`），因此本读取器不重复声明
    // 任何东西，也不可能与读同一视图的构建期合同检查分歧。
    values.insert(
        "handle_traits".to_owned(),
        face.string_list("handle_traits")
            .unwrap_or_default()
            .join(","),
    );
    values.insert(
        "handle_contracts".to_owned(),
        face.path_list("handle_contracts")
            .unwrap_or_default()
            .join(","),
    );
    values.insert(
        "part_contracts".to_owned(),
        face.path_list("part_contracts")
            .unwrap_or_default()
            .join(","),
    );
    values.insert(
        "part_traits".to_owned(),
        face.string_list("part_traits")
            .unwrap_or_default()
            .join(","),
    );
    values.insert(
        "requires".to_owned(),
        face.requirements("requires")
            .unwrap_or_default()
            .into_iter()
            .map(|(capability, provider)| format!("{capability}=>{provider}"))
            .collect::<Vec<_>>()
            .join(","),
    );
    values.insert(
        "provides".to_owned(),
        face.string_list("provides").unwrap_or_default().join(","),
    );
    values.insert(
        "runtime_checks".to_owned(),
        RuntimeCheckSpec::parse_list(face.field("runtime_checks").as_deref().unwrap_or(""))?
            .into_iter()
            .map(RuntimeCheckSpec::expression)
            .collect::<Vec<_>>()
            .join(","),
    );
    values.insert(
        "flow".to_owned(),
        parse_flow_field(face.field("flow").as_deref().unwrap_or(""))?,
    );
    values.insert(
        "flow_provider".to_owned(),
        // `path` first, then `string`: the macro spelling normalizes a bare path, while a face written as a
        // `Registration` literal carries `Some("crate::ControlHandle")` — and reading only the first made the
        // field come back empty for every literal face (`flow_provider -` in the readback, measured).
        // 先 `path` 再退 `string`：宏拼法归一化成一条裸路径，而写成 `Registration` 字面量的面带的是
        // `Some("crate::ControlHandle")`——只问前者会让每个字面量面的这个字段读回空值（实测回读里是
        // `flow_provider -`）。
        face.path("flow_provider")
            .or_else(|| face.string("flow_provider"))
            .unwrap_or_default(),
    );

    values.insert(
        "declaration_line".to_owned(),
        face.location.line.to_string(),
    );

    let parent_syntax = face.parent();
    if declared_parent_registry.is_some() && parent_syntax.is_none() {
        return Err("parent-specific registration macro requires an explicit parent".to_owned());
    }
    let parent_syntax = parent_syntax.or(Some(ParentSyntax::Root));
    if let (Some(declared), Some(parent)) = (declared_parent_registry, parent_syntax.as_ref()) {
        let expected = match parent {
            ParentSyntax::Root => "root".to_owned(),
            ParentSyntax::FromPath { source, .. } => Path::new(source)
                .file_stem()
                .and_then(|stem| stem.to_str())
                .unwrap_or("root")
                .to_owned(),
            ParentSyntax::NodePath(module) => module
                .rsplit("::")
                .find(|segment| !segment.is_empty())
                .unwrap_or("root")
                .to_owned(),
        };
        if declared != expected {
            return Err(format!(
                "registration macro `{}_object!` does not match parent `{expected}`",
                declared
            ));
        }
    }
    match parent_syntax {
        Some(ParentSyntax::Root) => {
            let namespace = authoring_namespace();
            values.insert("namespace".to_owned(), namespace.clone());
            values.insert(
                "parent_node".to_owned(),
                root_node_id(&namespace).to_string(),
            );
            values.insert("parent_source".to_owned(), "<root>".to_owned());
            values.insert("parent_kind".to_owned(), "root".to_owned());
        }
        Some(ParentSyntax::FromPath { source, kind }) => {
            values.insert(
                "parent_node".to_owned(),
                NodeId::from_namespaced_path(&authoring_namespace(), &source, &kind).to_string(),
            );
            values.insert("parent_source".to_owned(), source);
            values.insert("parent_kind".to_owned(), kind);
        }
        // A Rust face under a parent declared in a native source names it through the generated
        // `xirang_external::<flat>` alias, not through a module path. Without this branch the parser
        // read that alias as a module path, failed, and **every later authoring call on the package**
        // failed on the face that had just been created (reproduced: one Rust-under-C++ add, then
        // `add` reports `generated face has an invalid parent path`).
        // 挂在本地源码声明的父级下的 Rust 面，经生成的 `xirang_external::<flat>` 别名点名它，而不是经模块
        // 路径。没有这一支，解析器会把别名当模块路径读、失败，于是**对该包的每一次后续创作调用**都因那个刚
        // 创建的面失败（已复现：一次 Rust-under-C++ 的 add 之后，`add` 报 `generated face has an invalid
        // parent path`）。
        Some(ParentSyntax::NodePath(module)) if module.contains("xirang_external::") => {
            let flat = module.split("xirang_external::").nth(1).unwrap_or("");
            #[cfg(feature = "lang-cpp")]
            {
                let (source, kind) = external_parent(flat)?;
                values.insert("parent_source".to_owned(), source.clone());
                values.insert("parent_kind".to_owned(), kind.clone());
                values.insert(
                    "parent_node".to_owned(),
                    NodeId::from_namespaced_path(&authoring_namespace(), &source, &kind)
                        .to_string(),
                );
            }
            #[cfg(not(feature = "lang-cpp"))]
            {
                return Err(format!(
                    "`xirang_external::{flat}` names a parent declared in a native source, and this \
                     build does not carry the C++ adapter that reads those declarations; enable \
                     `xirang-toolchain` features = [\"lang-cpp\"] to author under it"
                ));
            }
        }
        Some(ParentSyntax::NodePath(module)) => {
            // The generated spelling ends in `::NODE_ID`; the address it names is the part before it.
            // 生成的拼法以 `::NODE_ID` 结尾；它点名的地址是它前面那一段。
            let module = module.strip_suffix("::NODE_ID").unwrap_or(&module);
            // The module address the file **declares** is a fact the renderer has to write back
            // verbatim. Deriving it from `parent_source` instead is only correct while the scan root
            // and the identity base coincide: under a custom `[lib] path`, the parent's record
            // spelling is `host/panel/panel.rs` while its module is `panel`, so a rewrite that
            // re-derived it emitted `.under(crate::host::panel::NODE_ID)` — a path that does not
            // resolve (measured: the generated host stopped compiling after one edit).
            // 文件**声明**的模块地址是渲染器必须原样写回的事实。改从 `parent_source` 推导只在扫描根与身份
            // 基准重合时正确：自定义 `[lib] path` 下父级的记录拼写是 `host/panel/panel.rs`，而它的模块是
            // `panel`，于是重新推导的改写会发射 `.under(crate::host::panel::NODE_ID)`——一个解析不到的
            // 路径（实测：一次编辑之后生成的宿主编译不过）。
            values.insert(
                "parent_module".to_owned(),
                module.strip_prefix("crate::").unwrap_or(module).to_owned(),
            );
            // The module spelling is turned into the record spelling by prefixing the layout's
            // scan-root offset (`source/` for `[lib] path = "source/lib.rs"`, empty for `src/`). The
            // offset is the layout's one fact, passed in by the reader that resolved it.
            // 模块拼写转成记录拼写时，加上布局的扫描根偏移（`[lib] path = "source/lib.rs"` 时是
            // `source/`，`src/` 时为空）。偏移是布局的一个事实，由解析该布局的读取方传入。
            let (source, kind) = match parents {
                // A reader handed the discovered tree in: the parent's record spelling and kind are
                // **facts**, and a module missing from that tree is a refusal — falling back to the
                // historical reconstruction would silently answer for a tree this reader did not see.
                // 读取方把已发现的树交进来了：父级的记录拼写与 kind 是**事实**，而树里没有那个模块就是
                // 拒绝——回退到历史的重建会为一个这个读取方没看见的树作答。
                Some(parents) => {
                    // The table is keyed by the module chain as the generated tree spells it,
                    // without the `crate::` prefix the declaration adds.
                    // 表以生成树写出的模块链为键，不带声明加上的 `crate::` 前缀。
                    let chain = module.strip_prefix("crate::").unwrap_or(module);
                    let facts = parents.get(chain).ok_or_else(|| {
                        format!(
                            "parent module `{module}` is not in this package's discovered modules;                              no record spelling is reconstructed from it"
                        )
                    })?;
                    (facts.source.clone(), facts.kind.clone())
                }
                // No tree was handed in (a direct unit call); keep the historical derivation.
                // 没有交进树（直接的单元调用）；保留历史推导。
                None => {
                    let source = format!(
                        "{identity_prefix}{}",
                        module_source_from_node_path(module)
                            .ok_or_else(|| "generated face has an invalid parent path".to_owned())?
                    );
                    let kind = kind_from_source_path(&source)
                        .ok_or_else(|| "generated face has an invalid parent path".to_owned())?;
                    (source, kind)
                }
            };
            values.insert("parent_source".to_owned(), source.clone());
            values.insert("parent_kind".to_owned(), kind.clone());
            values.insert(
                "parent_node".to_owned(),
                NodeId::from_namespaced_path(&authoring_namespace(), &source, &kind).to_string(),
            );
        }
        None => return Err("generated face has an invalid parent path".to_owned()),
    }
    values.insert(
        "registration_rule".to_owned(),
        rule_syntax_for_source(path)?,
    );
    Ok(FaceManifest { values })
}

#[cfg(feature = "lang-cpp")]
/// Resolve one generated `xirang_external::<flat>` alias to the declaration that owns it.
/// 把一个生成的 `xirang_external::<flat>` 别名解析回拥有它的那条声明。
///
/// The alias is `flat(module_of(source), name)`, and both inputs are in the declaration text — so the
/// package's native sources answer it without the compiler and without a record.
/// 别名是 `flat(module_of(source), name)`，两个输入都在声明文本里——因此本包的本地源码不需要编译器、
/// 也不需要记录就能回答它。
fn external_parent(flat: &str) -> Result<(String, String), String> {
    let root = crate::run_method::authoring::context::package_root();
    let faces = xirang_multilang::cpp_native::read_recipe(&root)
        .map_err(|error| format!("cannot read this package's native declarations: {error}"))?
        .map(|(_recipe, faces)| faces)
        .unwrap_or_default();
    for face in &faces {
        let module = xirang_multilang::cpp_native::module_of(&face.source);
        if xirang_multilang::cpp_names::flat(&module, &face.name) == flat {
            return Ok((face.source.clone(), face.name.clone()));
        }
    }
    Err(format!(
        "`xirang_external::{flat}` names no face this package's native sources declare; the aliases \
         they do declare are {}",
        if faces.is_empty() {
            "none (this package declares no native source)".to_owned()
        } else {
            faces
                .iter()
                .map(|face| {
                    let module = xirang_multilang::cpp_native::module_of(&face.source);
                    format!(
                        "`xirang_external::{}`",
                        xirang_multilang::cpp_names::flat(&module, &face.name)
                    )
                })
                .collect::<Vec<_>>()
                .join(", ")
        }
    ))
}
