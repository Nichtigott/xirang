//! Resolve generated registration faces without escaping the active package.
//! 在不越出当前包的前提下解析生成的注册面。

use super::*;

pub(super) fn generated_paths(
    registry: &Registry,
    id: NodeId,
) -> Result<(String, PathBuf), String> {
    let face = registry
        .find_registry(id)
        .ok_or_else(|| format!("node `{id}` is not registered"))?;
    let declared = Path::new(&face.source.file);
    let root = identity_base()?;
    let source = if declared.is_absolute() {
        // Absolute collector paths are editable only after canonicalization
        // proves that they still live below this package's source root.
        let canonical_root = fs::canonicalize(&root)
            .map_err(|error| format!("cannot resolve package source root: {error}"))?;
        let canonical_source = fs::canonicalize(declared)
            .map_err(|error| format!("cannot resolve registration source: {error}"))?;
        if !canonical_source.starts_with(&canonical_root) {
            return Err("only package-local generated modules can be edited".to_owned());
        }
        canonical_source
    } else {
        if declared.components().any(is_parent_component) {
            return Err("only package-local generated modules can be edited".to_owned());
        }
        // A record spelling is written against one of the layout's two bases: a face under the
        // library target keeps the identity-base-relative spelling, and a face an explicit placement
        // put outside the walk root keeps its package-relative one. The locator folds each candidate
        // back through the build's own rule, so the spelling — not "which file exists" — decides.
        // 记录拼写写的是布局两个基准之一：库目标下的面保留相对身份基准的拼写，显式落点放在遍历根之外的
        // 面保留包内相对拼写。定位器把每个候选按构建自己的规则折叠回去，因此决定的是拼写，而不是
        // "哪个文件存在"。
        let layout = crate::run_method::authoring::context::layout()?;
        xirang_multilang::source_ref::locate_record_spelling(
            &layout.package_root,
            &layout.identity_base,
            &face.source.file,
        )?
    };
    let relative = source.strip_prefix(&root).unwrap_or(declared);
    let text = fs::read_to_string(&source)
        .map_err(|_| "this module was not generated by XiRang".to_owned())?;
    if !is_xirang_owned_source(relative, &text) {
        return Err("this module was not generated by XiRang".to_owned());
    }
    Ok((face.registry_name.to_owned(), source))
}

fn is_xirang_owned_source(relative: &Path, text: &str) -> bool {
    text.lines().any(|line| line == GENERATED_MARKER)
        || (relative == Path::new("control/control.rs")
            && text.contains("pub struct ControlRegistry;")
            && text.contains("registry_rule_path:")
            && text.contains("registry_rule:"))
}
