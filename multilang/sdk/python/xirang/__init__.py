"""The Python side of a XiRang registration face.

A face written in Python declares itself with one decorator:

    from xirang import soil, faces

    @soil.face(
        under=faces.shop.panel.NODE_ID,
        named="Gauge",
        exports=("gauge",),
        needs_registry=False,
    )
    class Gauge:
        pass

The decorator returns the class unchanged: the declaration is metadata the build reads, not a
runtime transformation. `faces` is the generated object directory; the build writes it from the
same identities the Rust and C++ halves use, so a Python face hangs under a Rust parent by naming
the same constant.
"""


class _Soil:
    """The decorator namespace a face declaration uses.

    `@soil.face(...)` accepts the standard registration fields as keyword arguments and returns the
    class it decorates. An unknown keyword is kept as written by the authoring adapter and never
    silently dropped; the build reads the same keywords.
    """

    def face(self, cls=None, **fields):
        if cls is None:
            return lambda decorated: decorated
        return cls


soil = _Soil()


class _Directory:
    """A generated object directory: attribute access walks the logical tree.

    The real module is generated by the build with one attribute per face path; this fallback
    exists so a source file imports and type-checks before the first build, and so an editor can
    resolve `.under(…)` without a generated file being present.
    """

    def __getattr__(self, name):
        if name.startswith("__"):
            raise AttributeError(name)
        return _Directory()


faces = _Directory()
