//! The code a plan generates: the C ABI header, the C++ wrapper that carries it, and the
//! `ctypes` module a Python consumer imports.
//! 计划生成的代码：C ABI 头文件、承载它的 C++ 包装器，以及 Python 消费者导入的 `ctypes` 模块。

use xirang_kernel::interchange::{Export, ParameterType, ReturnType, Scalar};

/// The C ABI header generated from `[[export]]` and the typedefs it carries.
/// 由 `[[export]]` 生成的 C ABI 头文件，以及它携带的 typedef 集合。
fn header(
    name: &str,
    exports: &[Export],
) -> Result<(String, std::collections::BTreeSet<String>), String> {
    let guard = format!("XIRANG_{}_EXPORTS_H", name.to_uppercase().replace('-', "_"));
    let mut header = String::new();
    header.push_str(
        "/* Generated by xirang from the [[export]] tables in xirang.toml. Do not edit. */\n",
    );
    header.push_str(&format!("#ifndef {guard}\n#define {guard}\n\n"));
    header.push_str("#include <stdbool.h>\n#include <stddef.h>\n#include <stdint.h>\n\n");
    header.push_str("#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n");
    let mut typedefs = std::collections::BTreeSet::new();
    for export in exports {
        if let Some(kind) = &export.returns
            && let Some(typedef) = kind.c_typedef()?
        {
            typedefs.insert(typedef);
        }
        for (_, kind) in &export.parameters {
            if let Some(typedef) = kind.c_typedef() {
                typedefs.insert(typedef);
            }
        }
        if let Some(typedef) = export.c_error_typedef() {
            typedefs.insert(typedef);
        }
    }
    for typedef in &typedefs {
        header.push_str(typedef);
        header.push('\n');
    }
    if !typedefs.is_empty() {
        header.push('\n');
    }
    for export in exports {
        let prototype = export.c_prototype()?;
        header.push_str(&prototype);
        header.push_str(";\n");
    }
    header.push_str("\n#ifdef __cplusplus\n}\n#endif\n\n#endif\n");
    Ok((header, typedefs))
}

/// The C ABI header and the C++ wrapper that carries it, generated from `[[export]]`.
/// 由 `[[export]]` 生成的 C ABI 头文件与承载它的 C++ 包装器。
///
/// The header is what a consumer in another language includes; the wrapper is the only C++
/// translation unit this plan invents, so the export reaches the C boundary without the user
/// writing `extern "C"` a second time.
/// 头文件是另一种语言的消费者所包含的东西；包装器是本计划唯一生成的 C++ 编译单元，因此导出能到达
/// C 边界，而用户不必再写一遍 `extern "C"`。
pub(super) fn generated_exports(
    name: &str,
    exports: &[Export],
) -> Result<(String, String), String> {
    let (header, typedefs) = header(name, exports)?;
    // The wrapper cannot include the generated header: it declares the C symbol under the export's
    // name, which would collide with the implementation the wrapper forwards to. Instead it
    // declares the implementation, and defines the C symbol under a distinct name with the export's
    // name as its assembler label. `g++`/`clang++` both implement the label.
    // 包装器不能包含生成的头文件：头文件用导出名声明 C 符号，会与它要转发的实现同名冲突。
    // 因此包装器声明实现，并给 C 符号一个不同的名字、把导出名作为汇编标签。
    let mut wrapper = String::from(
        "// Generated by xirang. Do not edit.\n#include <cstddef>\n#include <cstdint>\n#include <cstring>\n#include <expected>\n#include <optional>\n#include <string>\n#include <string_view>\n\n",
    );
    // The wrapper cannot include the generated header (the C symbols would collide with the C++
    // implementations it forwards to), so it repeats the typedefs the header carries.
    // 包装器不能包含生成的头文件（C 符号会与它转发的 C++ 实现冲突），因此它重复头文件里的 typedef。
    for typedef in &typedefs {
        wrapper.push_str(typedef);
        wrapper.push('\n');
    }
    if !typedefs.is_empty() {
        wrapper.push('\n');
    }
    for (index, export) in exports.iter().enumerate() {
        let returns = if export.errors.is_empty() {
            match &export.returns {
                Some(kind) => kind.c_return_type()?,
                None => "void".to_owned(),
            }
        } else {
            "int32_t".to_owned()
        };
        let implementation_returns = if !export.errors.is_empty() {
            let Some(ReturnType::Scalar(scalar)) = &export.returns else {
                return Err(format!(
                    "`{}` declares typed errors without a scalar return; this slice only carries \
                     them beside one",
                    export.name
                ));
            };
            format!("std::expected<{}, std::int32_t>", scalar.c_return()?)
        } else {
            match &export.returns {
                Some(ReturnType::Scalar(scalar)) => scalar.c_return()?.to_owned(),
                Some(ReturnType::Text) | Some(ReturnType::Bytes) => "std::string".to_owned(),
                Some(ReturnType::Optional(scalar)) => {
                    format!("std::optional<{}>", scalar.c_return()?)
                }
                None => "void".to_owned(),
            }
        };
        let implementation_parameters: Vec<String> = export
            .parameters
            .iter()
            .map(|(_, kind)| match kind {
                ParameterType::Scalar(Scalar::Utf8 | Scalar::Bytes) => {
                    "std::string_view".to_owned()
                }
                ParameterType::Scalar(other) => other.c_return().unwrap_or("void").to_owned(),
                ParameterType::Optional(scalar) => {
                    format!("std::optional<{}>", scalar.c_return().unwrap_or("void"))
                }
            })
            .collect();
        wrapper.push_str(&format!(
            "{implementation_returns} {}({});\n\n",
            export.name,
            implementation_parameters.join(", ")
        ));
        let mut c_parameters: Vec<String> = export
            .parameters
            .iter()
            .enumerate()
            .map(|(position, (_, kind))| kind.c_parameter(&format!("p{position}")))
            .collect();
        // A text or bytes return is written into a buffer the caller owns: the call reports the
        // length it needs, and copies only when the buffer is large enough.
        // 文本或字节返回写进调用方拥有的缓冲区：调用报告所需长度，只在缓冲区足够大时才复制。
        if let Some(kind) = &export.returns
            && let Some(buffer) = kind.buffer()
        {
            c_parameters.push(format!("{buffer} *out"));
            c_parameters.push("size_t cap".to_owned());
            c_parameters.push("size_t *out_len".to_owned());
        }
        if !export.errors.is_empty() {
            let Some(ReturnType::Scalar(scalar)) = &export.returns else {
                return Err(format!(
                    "`{}` declares typed errors without a scalar return",
                    export.name
                ));
            };
            c_parameters.push(format!("{} *out", scalar.c_return()?));
            c_parameters.push(format!("{} *error", export.error_enum()));
        }
        let symbol = format!("xirang_export_{index}");
        wrapper.push_str(&format!(
            "extern \"C\" {returns} {symbol}({}) __asm__(\"{}\");\n",
            c_parameters.join(", "),
            export.name
        ));
        wrapper.push_str(&format!(
            "extern \"C\" {returns} {symbol}({}) {{\n",
            c_parameters.join(", ")
        ));
        let arguments: Vec<String> = export
            .parameters
            .iter()
            .enumerate()
            .map(|(position, (_, kind))| {
                let parameter = format!("p{position}");
                match kind {
                    ParameterType::Scalar(Scalar::Utf8) => {
                        format!("std::string_view({parameter}, {parameter}_len)")
                    }
                    ParameterType::Scalar(Scalar::Bytes) => format!(
                        "std::string_view(reinterpret_cast<const char *>({parameter}), \
                         {parameter}_len)"
                    ),
                    ParameterType::Scalar(_) => parameter,
                    ParameterType::Optional(scalar) => format!(
                        "({parameter}.present ? std::optional<{ctype}>({parameter}.value) : \
                         std::nullopt)",
                        ctype = scalar.c_return().unwrap_or("void")
                    ),
                }
            })
            .collect();
        let call = format!("::{}({})", export.name, arguments.join(", "));
        let body = if !export.errors.is_empty() {
            let Some(ReturnType::Scalar(scalar)) = &export.returns else {
                return Err(format!(
                    "`{}` declares typed errors without a scalar return",
                    export.name
                ));
            };
            format!(
                "    std::expected<{ctype}, std::int32_t> value = {call};\n    if \
                 (value.has_value()) {{\n        *out = *value;\n        *error = \
                 static_cast<{enum}>(0);\n        return 0;\n    }}\n    *error = \
                 static_cast<{enum}>(value.error());\n    return 1;",
                ctype = scalar.c_return()?,
                enum = export.error_enum()
            )
        } else {
            match &export.returns {
                Some(ReturnType::Scalar(_)) => format!("    return {call};"),
                Some(ReturnType::Text) | Some(ReturnType::Bytes) => format!(
                    "    std::string value = {call};\n    *out_len = value.size();\n    if (out == \
                 nullptr || cap < value.size()) {{\n        return false;\n    }}\n    \
                 std::memcpy(out, value.data(), value.size());\n    return true;"
                ),
                Some(ReturnType::Optional(scalar)) => format!(
                    "    std::optional<{ctype}> value = {call};\n    {name} result{{}};\n    \
                 result.present = value.has_value();\n    if (value) {{\n        \
                 result.value = *value;\n    }}\n    return result;",
                    ctype = scalar.c_return()?,
                    name = ReturnType::struct_name(*scalar)
                ),
                None => format!("    {call};"),
            }
        };
        wrapper.push_str(&format!("{body}\n}}\n\n"));
    }
    Ok((header, wrapper))
}

pub(super) fn python_exports(name: &str, exports: &[Export]) -> Result<String, String> {
    let library = format!("lib{}.so", name.replace('-', "_"));
    let mut text = format!(
        "\"\"\"Generated by xirang from the `[[export]]` tables in xirang.toml. Do not edit.\"\"\"\n\
         import ctypes\n\
         from pathlib import Path\n\n\
         _LIBRARY = ctypes.CDLL(str(Path(__file__).with_name(\"{library}\")))\n"
    );
    let mut optional_classes: Vec<Scalar> = Vec::new();
    for export in exports {
        if let Some(ReturnType::Optional(scalar)) = &export.returns
            && !optional_classes.contains(scalar)
        {
            optional_classes.push(*scalar);
        }
        for (_, kind) in &export.parameters {
            if let ParameterType::Optional(scalar) = kind
                && !optional_classes.contains(scalar)
            {
                optional_classes.push(*scalar);
            }
        }
    }
    for scalar in &optional_classes {
        text.push_str(&format!(
            "\n\nclass {}(ctypes.Structure):\n    _fields_ = [(\"present\", ctypes.c_bool), (\"value\", {})]\n",
            ReturnType::struct_name(*scalar),
            ctypes_type(*scalar)
        ));
    }
    for export in exports {
        if export.errors.is_empty() {
            continue;
        }
        let variants = export
            .errors
            .iter()
            .enumerate()
            .map(|(position, variant)| format!("{}: \"{variant}\"", position + 1))
            .collect::<Vec<_>>()
            .join(", ");
        text.push_str(&format!(
            "\n\nclass {}(Exception):\n    VARIANTS = {{{variants}}}\n",
            error_class(&export.name)
        ));
    }
    let has_optional_parameter = exports.iter().any(|export| {
        export
            .parameters
            .iter()
            .any(|(_, kind)| matches!(kind, ParameterType::Optional(_)))
    });
    if has_optional_parameter {
        text.push_str(
            "\n\ndef _optional(value, structure, underlying):\n    if value is None:\n        return structure()\n    return structure(True, underlying(value))\n",
        );
    }
    for export in exports {
        let prototype = export.c_prototype()?;
        let parameters: Vec<String> = export
            .parameters
            .iter()
            .map(|(parameter, _)| (*parameter).to_owned())
            .collect();
        let returns_text = matches!(export.returns, Some(ReturnType::Text));
        let returns_bytes = matches!(export.returns, Some(ReturnType::Bytes));
        let returns_optional = matches!(export.returns, Some(ReturnType::Optional(_)));
        let returns_error = !export.errors.is_empty();
        let error = error_class(&export.name);
        let annotation = if returns_text {
            "str"
        } else if returns_bytes {
            "bytes"
        } else {
            "object"
        };
        text.push_str(&format!(
            "\n\ndef {}({}) -> {annotation}:\n    \"\"\"{prototype}\"\"\"\n",
            export.name,
            parameters.join(", ")
        ));
        let mut argtypes = Vec::new();
        for (index, (parameter, kind)) in export.parameters.iter().enumerate() {
            match kind {
                ParameterType::Scalar(Scalar::Utf8 | Scalar::Bytes) => {
                    text.push_str(&format!(
                        "    _p{index} = {parameter}.encode(\"utf-8\") if isinstance({parameter}, str) else {parameter}\n"
                    ));
                    argtypes.push("ctypes.c_char_p".to_owned());
                    argtypes.push("ctypes.c_size_t".to_owned());
                }
                ParameterType::Scalar(scalar) => argtypes.push(ctypes_type(*scalar).to_owned()),
                ParameterType::Optional(scalar) => {
                    argtypes.push(ReturnType::struct_name(*scalar));
                }
            }
        }
        if returns_error {
            let Some(ReturnType::Scalar(scalar)) = &export.returns else {
                return Err(format!(
                    "`{}` declares typed errors without a scalar return",
                    export.name
                ));
            };
            argtypes.push(format!("ctypes.POINTER({})", ctypes_type(*scalar)));
            argtypes.push("ctypes.POINTER(ctypes.c_int32)".to_owned());
        }
        if returns_text || returns_bytes {
            argtypes.push("ctypes.c_void_p".to_owned());
            argtypes.push("ctypes.c_size_t".to_owned());
            argtypes.push("ctypes.POINTER(ctypes.c_size_t)".to_owned());
        }
        text.push_str(&format!(
            "    _LIBRARY.{}.argtypes = [{}]\n",
            export.name,
            argtypes.join(", ")
        ));
        let restype = if returns_error {
            "ctypes.c_int32".to_owned()
        } else {
            match &export.returns {
                Some(ReturnType::Scalar(scalar)) => ctypes_type(*scalar).to_owned(),
                Some(ReturnType::Optional(scalar)) => ReturnType::struct_name(*scalar),
                Some(_) => "ctypes.c_bool".to_owned(),
                None => "None".to_owned(),
            }
        };
        text.push_str(&format!(
            "    _LIBRARY.{}.restype = {restype}\n",
            export.name
        ));
        let mut arguments = Vec::new();
        for (index, (parameter, kind)) in export.parameters.iter().enumerate() {
            match kind {
                ParameterType::Scalar(Scalar::Utf8 | Scalar::Bytes) => {
                    arguments.push(format!("_p{index}, len(_p{index})"));
                }
                ParameterType::Scalar(_) => arguments.push((*parameter).to_owned()),
                ParameterType::Optional(scalar) => arguments.push(format!(
                    "_optional({parameter}, {}, {})",
                    ReturnType::struct_name(*scalar),
                    ctypes_type(*scalar)
                )),
            }
        }
        if returns_error {
            let Some(ReturnType::Scalar(scalar)) = &export.returns else {
                return Err(format!(
                    "`{}` declares typed errors without a scalar return",
                    export.name
                ));
            };
            text.push_str(&format!(
                "    _out = {}()\n    _error = ctypes.c_int32()\n",
                ctypes_type(*scalar)
            ));
            let mut call_arguments = arguments.clone();
            call_arguments.push("ctypes.byref(_out)".to_owned());
            call_arguments.push("ctypes.byref(_error)".to_owned());
            text.push_str(&format!(
                "    _status = _LIBRARY.{}({})\n    if _status != 0:\n        raise {}({}.VARIANTS.get(_error.value, \"unknown\"))\n    return _out.value\n",
                export.name,
                call_arguments.join(", "),
                error,
                error
            ));
        } else if returns_optional {
            text.push_str(&format!(
                "    _result = _LIBRARY.{}({})\n    return _result.value if _result.present else None\n",
                export.name,
                arguments.join(", ")
            ));
        } else if returns_text || returns_bytes {
            text.push_str("    _out_len = ctypes.c_size_t(0)\n");
            let mut sizing = arguments.clone();
            sizing.push("None".to_owned());
            sizing.push("0".to_owned());
            sizing.push("ctypes.byref(_out_len)".to_owned());
            text.push_str(&format!(
                "    _LIBRARY.{}({})\n",
                export.name,
                sizing.join(", ")
            ));
            text.push_str("    _out = ctypes.create_string_buffer(max(_out_len.value, 1))\n");
            let mut call_arguments = arguments.clone();
            call_arguments.push("ctypes.cast(_out, ctypes.c_void_p)".to_owned());
            call_arguments.push("_out_len.value".to_owned());
            call_arguments.push("ctypes.byref(_out_len)".to_owned());
            text.push_str(&format!(
                "    if not _LIBRARY.{}({}):\n        raise ValueError(\"{} could not be called\")\n",
                export.name,
                call_arguments.join(", "),
                export.name
            ));
            if returns_text {
                text.push_str("    return _out.raw[:_out_len.value].decode(\"utf-8\")\n");
            } else {
                text.push_str("    return _out.raw[:_out_len.value]\n");
            }
        } else {
            let call = format!("_LIBRARY.{}({})", export.name, arguments.join(", "));
            if export.returns.is_some() {
                text.push_str(&format!("    return {call}\n"));
            } else {
                text.push_str(&format!("    {call}\n"));
            }
        }
    }
    Ok(text)
}

/// `checked_div` becomes `CheckedDivError`, the name of the generated exception.
/// `checked_div` 变成 `CheckedDivError`，即生成异常类的名字。
fn error_class(name: &str) -> String {
    let mut text = String::new();
    for part in name.split('_') {
        let mut characters = part.chars();
        if let Some(first) = characters.next() {
            text.push(first.to_ascii_uppercase());
            text.extend(characters);
        }
    }
    text.push_str("Error");
    text
}

/// The `ctypes` spelling of one interchange scalar.
/// 一个交换标量的 `ctypes` 拼写。
fn ctypes_type(scalar: Scalar) -> &'static str {
    match scalar {
        Scalar::I8 => "ctypes.c_int8",
        Scalar::I16 => "ctypes.c_int16",
        Scalar::I32 => "ctypes.c_int32",
        Scalar::I64 => "ctypes.c_int64",
        Scalar::U8 => "ctypes.c_uint8",
        Scalar::U16 => "ctypes.c_uint16",
        Scalar::U32 => "ctypes.c_uint32",
        Scalar::U64 => "ctypes.c_uint64",
        Scalar::F32 => "ctypes.c_float",
        Scalar::F64 => "ctypes.c_double",
        Scalar::Bool => "ctypes.c_bool",
        Scalar::Utf8 | Scalar::Bytes => "ctypes.c_char_p",
    }
}

/// The C ABI header and the Rust wrapper that carries it, generated from `[[export]]`.
/// 由 `[[export]]` 生成的 C ABI 头文件与承载它的 Rust 包装器。
///
/// A Rust producer is a staticlib: the wrapper compiles the user's rlib into a staticlib whose
/// `#[no_mangle] extern "C"` functions have the export names, so a C consumer links it like any
/// other archive. Fixed-width scalars, `bool` and optional scalars cross in this slice — an optional
/// parameter arrives as the same struct the C header carries and the wrapper converts it to
/// `Option`; text and bytes parameters, and text, bytes, optional and typed-error *returns*, are
/// refused by name rather than silently mistranslated.
/// Rust 生产者是一份 staticlib：包装器把用户的 rlib 编成 staticlib，其 `#[no_mangle] extern "C"`
/// 函数用导出名，于是 C 消费者像链接任何归档一样链接它。本切片过固定宽度标量、`bool` 与可选标量
/// ——可选参数以 C 头文件携带的同一个结构体到达，包装器把它转换成 `Option`；文本/bytes 参数，以及
/// 文本、bytes、可选与类型化错误的**返回**，按名拒绝，而不是被静默地错误翻译。
pub(super) fn generated_rust_exports(
    name: &str,
    exports: &[Export],
) -> Result<(String, String), String> {
    let (header, _) = header(name, exports)?;
    let crate_name = name.replace('-', "_");
    let mut wrapper = format!(
        "// Generated by xirang from the [[export]] tables in xirang.toml. Do not edit.\n\
         //\n\
         // Each export becomes one `#[no_mangle]` `extern \"C\"` function so the generated header\n\
         // finds a symbol with the export's own name.\n\
         extern crate {crate_name};\n\n"
    );
    // An optional parameter arrives as the struct the header carries (`present` plus the value);
    // the wrapper converts it to the `Option` the user's function takes, so the two sides agree on
    // one layout instead of the wrapper inventing a second one.
    // 可选参数以头文件携带的结构体到达（`present` 加值）；包装器把它转换成用户函数接受的
    // `Option`，于是两侧共用一套布局，而不是由包装器另造一套。
    let mut optional_scalars: Vec<Scalar> = Vec::new();
    for export in exports {
        for (_, kind) in &export.parameters {
            if let ParameterType::Optional(scalar) = kind
                && !optional_scalars.contains(scalar)
            {
                optional_scalars.push(*scalar);
            }
        }
    }
    for scalar in &optional_scalars {
        wrapper.push_str(&format!(
            "// The C struct `{struct_name}` from the generated header, by value.\n\
             // 生成头文件里的 C 结构体 `{struct_name}`，按值传递。\n\
             #[allow(non_camel_case_types)]\n\
             #[repr(C)]\n\
             pub struct {struct_name} {{ pub present: bool, pub value: {value} }}\n\n",
            struct_name = ReturnType::struct_name(*scalar),
            value = scalar.token(),
        ));
    }
    for export in exports {
        if !export.errors.is_empty() {
            return Err(format!(
                "`{}` declares typed errors; a Rust producer carries them in a later slice",
                export.name
            ));
        }
        let mut parameters = Vec::new();
        let mut names = Vec::new();
        for (parameter, kind) in &export.parameters {
            match kind {
                ParameterType::Scalar(scalar) => {
                    if matches!(scalar, Scalar::Utf8 | Scalar::Bytes) {
                        return Err(format!(
                            "`{}` takes a `{}` parameter; a Rust producer carries fixed-width \
                             scalars and booleans in this slice",
                            export.name,
                            scalar.token()
                        ));
                    }
                    parameters.push(format!("{parameter}: {}", scalar.token()));
                    names.push((*parameter).to_owned());
                }
                // The wrapper keeps the caller's struct as the C type and converts at the one place
                // where the value crosses into the user's function.
                // 包装器把调用方的结构体保留为 C 类型，只在这个值进入用户函数的那一处转换。
                ParameterType::Optional(scalar) => {
                    parameters.push(format!("{parameter}: {}", ReturnType::struct_name(*scalar)));
                    names.push(format!(
                        "if {parameter}.present {{ Some({parameter}.value) }} else {{ None }}"
                    ));
                }
            }
        }
        let returns = match &export.returns {
            Some(ReturnType::Scalar(scalar)) => format!(" -> {}", scalar.token()),
            Some(other) => {
                return Err(format!(
                    "`{}` returns `{}`; a Rust producer carries fixed-width scalar returns in \
                     this slice",
                    export.name,
                    other.c_return_type()?
                ));
            }
            None => String::new(),
        };
        wrapper.push_str(&format!(
            "#[no_mangle]\npub extern \"C\" fn {}({}){returns} {{\n    {crate_name}::{}({})\n}}\n\n",
            export.name,
            parameters.join(", "),
            export.name,
            names.join(", ")
        ));
    }
    Ok((header, wrapper))
}
