//! Consumer bindings generated from a project's `[[export]]` declarations: the declarations are
//! already the contract, so a starter for a consumer does not need the build directory or a
//! reverse-engineering pass. This slice emits the **scalar subset plus optional scalars** for Python
//! (ctypes), C# (P/Invoke), Go (cgo) and Rust (`extern "C"` declarations); an optional parameter is
//! carried as the same `present`-flag struct the generated C header lays out, and each starter maps
//! it to the shape its language can actually pass by value. Ruby (Fiddle) passes scalars and
//! pointers only, so it refuses an optional parameter by name instead of pretending. Text, bytes
//! and typed errors stay refused everywhere: they need caller-owned buffers or status/out-parameter
//! protocols that a pasted starter cannot honestly guess.
//! 由项目的 `[[export]]` 声明生成消费端绑定：声明本身就是契约，因此消费端的起点不需要读构建目录、
//! 也不需要反向推导。本切片为 Python（ctypes）、C#（P/Invoke）、Go（cgo）与 Rust（`extern "C"` 声明）
//! 生成**标量子集加可选标量**；可选参数以生成的 C 头文件布局的那个带 `present` 标志的结构体承载，
//! 每个起点把它映射成该语言真的能按值传递的形状。Ruby（Fiddle）只传标量与指针，因此对可选参数按名
//! 拒绝，而不是假装支持。text、bytes 与类型化错误在所有语言里都仍然拒绝——它们需要调用方缓冲区或
//! 状态/出参协议，一段可粘贴的起点无法诚实猜测。

use xirang_kernel::interchange::{Export, ParameterType, ReturnType, Scalar};

/// The consumers this generator writes starters for.
/// 本生成器为其写起点的消费端。
pub(super) const LANGUAGES: [&str; 5] = ["python", "csharp", "go", "rust", "ruby"];

/// One parameter a starter carries: a scalar by value, or an optional scalar as the C struct.
/// 起点携带的一个参数：按值传递的标量，或按 C 结构体传递的可选标量。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum BindingParameter {
    /// A plain scalar, passed as the language's own scalar type.
    /// 普通标量，按该语言自己的标量类型传递。
    Scalar(Scalar),
    /// An optional scalar, passed as `xirang_optional_<t>` by value.
    /// 可选标量，按值传递为 `xirang_optional_<t>`。
    Optional(Scalar),
}

/// One export as a starter can carry it: named parameters in call order, and the scalar return.
/// 一个导出在起点里能承载的形状：按调用顺序命名的参数，以及标量返回。
struct Signature {
    parameters: Vec<(String, BindingParameter)>,
    returns: Scalar,
}

/// The optional scalars these exports use, in the order they first appear.
/// 这些导出用到的可选标量，按首次出现的顺序。
fn optional_scalars(exports: &[Export]) -> Vec<Scalar> {
    let mut seen: Vec<Scalar> = Vec::new();
    for export in exports {
        for (_, kind) in &export.parameters {
            if let ParameterType::Optional(scalar) = kind
                && !seen.contains(scalar)
            {
                seen.push(*scalar);
            }
        }
    }
    seen
}

/// Render the bindings for one unit's exports in `language`.
/// 为 `language` 渲染一个单元的导出绑定。
pub(super) fn render(unit: &str, exports: &[Export], language: &str) -> Result<String, String> {
    if exports.is_empty() {
        return Err(format!(
            "unit `{unit}` declares no `[[export]]`; there is no cross-language contract to bind"
        ));
    }
    let mut out = String::new();
    match language {
        "python" => {
            out.push_str(&format!(
                "# Generated by `xirang bindings --language python` for unit `{unit}`.\n\
                 # The library is the shared object `lib{unit}.so`; put its directory on LD_LIBRARY_PATH.\n\
                 import ctypes\n\n\
                 library = ctypes.CDLL(\"lib{unit}.so\")\n"
            ));
            let optionals = optional_scalars(exports);
            for scalar in &optionals {
                out.push_str(&format!(
                    "\n\nclass {}(ctypes.Structure):\n    _fields_ = [(\"present\", ctypes.c_bool), (\"value\", ctypes.{})]\n",
                    ReturnType::struct_name(*scalar),
                    python_type(*scalar)
                ));
            }
            if !optionals.is_empty() {
                out.push_str(
                    "\n\ndef _optional(value, structure, underlying):\n    if value is None:\n        return structure()\n    return structure(True, underlying(value))\n",
                );
            }
            for export in exports {
                let signature = signature(export)?;
                let local = python_name(&export.name);
                let carriable = signature
                    .parameters
                    .iter()
                    .any(|(_, kind)| matches!(kind, BindingParameter::Optional(_)));
                // A starter that has to convert a value binds the ctypes function under a private
                // name and defines the public one, so a caller still passes a value or `None`.
                // 需要转换值的起点把 ctypes 函数绑在私有名字上，再定义公开的那个，于是调用方仍然
                // 传一个值或 `None`。
                let binding = if carriable {
                    format!("_{local}")
                } else {
                    local.clone()
                };
                let argtypes = signature
                    .parameters
                    .iter()
                    .map(|(_, kind)| match kind {
                        BindingParameter::Scalar(scalar) => {
                            format!("ctypes.{}", python_type(*scalar))
                        }
                        BindingParameter::Optional(scalar) => ReturnType::struct_name(*scalar),
                    })
                    .collect::<Vec<_>>()
                    .join(", ");
                let restype = format!("ctypes.{}", python_type(signature.returns));
                out.push_str(&format!(
                    "\n{binding} = library.{}\n{binding}.argtypes = [{argtypes}]\n{binding}.restype = {restype}\n",
                    export.name
                ));
                if carriable {
                    let names = signature
                        .parameters
                        .iter()
                        .map(|(name, _)| name.clone())
                        .collect::<Vec<_>>()
                        .join(", ");
                    let arguments = signature
                        .parameters
                        .iter()
                        .map(|(name, kind)| match kind {
                            BindingParameter::Scalar(_) => name.clone(),
                            BindingParameter::Optional(scalar) => format!(
                                "_optional({name}, {}, ctypes.{})",
                                ReturnType::struct_name(*scalar),
                                python_type(*scalar)
                            ),
                        })
                        .collect::<Vec<_>>()
                        .join(", ");
                    out.push_str(&format!(
                        "\n\ndef {local}({names}):\n    return {binding}({arguments})\n"
                    ));
                }
            }
            Ok(out)
        }
        "csharp" => {
            let exports_class = class_name(unit);
            out.push_str(&format!(
                "// Generated by `xirang bindings --language csharp` for unit `{unit}`.\n\
                 // The library is `lib{unit}.so`; put its directory on LD_LIBRARY_PATH.\n\
                 using System.Runtime.InteropServices;\n\n"
            ));
            for scalar in optional_scalars(exports) {
                out.push_str(&format!(
                    "[StructLayout(LayoutKind.Sequential)]\ninternal struct {struct_name}\n{{\n    \
                     [MarshalAs(UnmanagedType.I1)] public bool present;\n    public {value} value;\n}}\n\n",
                    struct_name = ReturnType::struct_name(scalar),
                    value = csharp_type(scalar)
                ));
            }
            out.push_str(&format!(
                "internal static class {exports_class}Exports\n{{\n"
            ));
            for export in exports {
                let signature = signature(export)?;
                out.push_str(&format!(
                    "    [DllImport(\"lib{unit}.so\")]\n    internal static extern {} {}({});\n",
                    csharp_type(signature.returns),
                    export.name,
                    signature
                        .parameters
                        .iter()
                        .map(|(name, kind)| match kind {
                            BindingParameter::Scalar(Scalar::Bool) => {
                                format!("[MarshalAs(UnmanagedType.I1)] bool {name}")
                            }
                            BindingParameter::Scalar(scalar) => {
                                format!("{} {name}", csharp_type(*scalar))
                            }
                            BindingParameter::Optional(scalar) => {
                                format!("{} {name}", ReturnType::struct_name(*scalar))
                            }
                        })
                        .collect::<Vec<_>>()
                        .join(", ")
                ));
            }
            out.push_str("}\n");
            Ok(out)
        }
        "go" => {
            let optionals = optional_scalars(exports);
            let mut preamble = String::new();
            for scalar in &optionals {
                preamble.push_str(&format!(
                    "typedef struct {{ bool present; {ctype} value; }} {struct_name};\n\
                     static inline {struct_name} {struct_name}_of(int present, {ctype} value) {{\n    \
                     {struct_name} result;\n    result.present = present != 0;\n    result.value = value;\n    \
                     return result;\n}}\n",
                    ctype = c_type(*scalar),
                    struct_name = ReturnType::struct_name(*scalar)
                ));
            }
            for export in exports {
                let signature = signature(export)?;
                preamble.push_str(&format!("{} {}(", c_type(signature.returns), export.name));
                preamble.push_str(
                    &signature
                        .parameters
                        .iter()
                        .map(|(name, kind)| match kind {
                            BindingParameter::Scalar(scalar) => {
                                format!("{} {name}", c_type(*scalar))
                            }
                            BindingParameter::Optional(scalar) => {
                                format!("{} {name}", ReturnType::struct_name(*scalar))
                            }
                        })
                        .collect::<Vec<_>>()
                        .join(", "),
                );
                preamble.push_str(");\n");
            }
            out.push_str(&format!(
                "// Generated by `xirang bindings --language go` for unit `{unit}`.\n\
                 // The library is `lib{unit}.so`; build with CGO_LDFLAGS=-L<its directory>.\n\
                 package {package}\n\n/*\n#cgo LDFLAGS: -l{unit}\n#include <stdint.h>\n#include <stdbool.h>\n{preamble}*/\nimport \"C\"\n",
                package = go_package(unit)
            ));
            for scalar in &optionals {
                let name = go_optional(*scalar);
                out.push_str(&format!(
                    "\n// {name} is the C struct `{c_name}`, passed by value.\n\
                     type {name} = C.{c_name}\n\n\
                     // Some{stem} builds the struct with a present value.\n\
                     func Some{stem}(value {gotype}) {name} {{\n    return C.{c_name}_of(1, C.{ctype}(value))\n}}\n\n\
                     // None{stem} builds the struct with no value.\n\
                     func None{stem}() {name} {{\n    return C.{c_name}_of(0, 0)\n}}\n",
                    c_name = ReturnType::struct_name(*scalar),
                    stem = class_name(scalar.token()),
                    gotype = go_type(*scalar),
                    ctype = c_type(*scalar),
                ));
            }
            for export in exports {
                let signature = signature(export)?;
                out.push_str(&format!(
                    "\n// {} is the generated wrapper for the C export.\nfunc {}({}) {} {{\n    return {}(C.{}({}))\n}}\n",
                    go_name(&export.name),
                    go_name(&export.name),
                    signature
                        .parameters
                        .iter()
                        .map(|(name, kind)| match kind {
                            BindingParameter::Scalar(scalar) => {
                                format!("{name} {}", go_type(*scalar))
                            }
                            BindingParameter::Optional(scalar) => {
                                format!("{name} {}", go_optional(*scalar))
                            }
                        })
                        .collect::<Vec<_>>()
                        .join(", "),
                    go_type(signature.returns),
                    go_type(signature.returns),
                    export.name,
                    signature
                        .parameters
                        .iter()
                        .map(|(name, kind)| match kind {
                            BindingParameter::Scalar(scalar) => {
                                format!("C.{}({name})", c_type(*scalar))
                            }
                            BindingParameter::Optional(_) => name.clone(),
                        })
                        .collect::<Vec<_>>()
                        .join(", "),
                ));
            }
            Ok(out)
        }
        "rust" => {
            out.push_str(&format!(
                "// Generated by `xirang bindings --language rust` for unit `{unit}`.\n\
                 // The library is `lib{unit}.so`; pass `-L <its directory> -l {unit}` to rustc.\n"
            ));
            for scalar in optional_scalars(exports) {
                out.push_str(&format!(
                    "\n// The C struct `{struct_name}` from the generated header, by value.\n\
                     #[allow(non_camel_case_types)]\n#[repr(C)]\npub struct {struct_name} {{ pub present: bool, pub value: {} }}\n",
                    rust_type(scalar),
                    struct_name = ReturnType::struct_name(scalar)
                ));
            }
            out.push_str("\nunsafe extern \"C\" {\n");
            for export in exports {
                let signature = signature(export)?;
                out.push_str(&format!(
                    "    pub fn {}({}) -> {};\n",
                    export.name.replace('-', "_"),
                    signature
                        .parameters
                        .iter()
                        .map(|(name, kind)| match kind {
                            BindingParameter::Scalar(scalar) => {
                                format!("{name}: {}", rust_type(*scalar))
                            }
                            BindingParameter::Optional(scalar) => {
                                format!("{name}: {}", ReturnType::struct_name(*scalar))
                            }
                        })
                        .collect::<Vec<_>>()
                        .join(", "),
                    rust_type(signature.returns)
                ));
            }
            out.push_str("}\n");
            Ok(out)
        }
        "ruby" => {
            let module = class_name(unit);
            out.push_str(&format!(
                "# Generated by `xirang bindings --language ruby` for unit `{unit}`.\n\
                 # The library is `lib{unit}.so`; put its directory on LD_LIBRARY_PATH.\n\
                 require \"fiddle\"\n\n\
                 module {module}\n  LIBRARY = Fiddle.dlopen(\"lib{unit}.so\")\n"
            ));
            for export in exports {
                let signature = signature(export)?;
                if signature
                    .parameters
                    .iter()
                    .any(|(_, kind)| matches!(kind, BindingParameter::Optional(_)))
                {
                    return Err(optional_refused_in_ruby(export));
                }
                let constant = export.name.to_uppercase().replace('-', "_");
                let types = signature
                    .parameters
                    .iter()
                    .map(|(_, kind)| match kind {
                        BindingParameter::Scalar(scalar) => {
                            format!("Fiddle::{}", ruby_type(*scalar))
                        }
                        BindingParameter::Optional(_) => {
                            unreachable!("refused above, before any text is written")
                        }
                    })
                    .collect::<Vec<_>>()
                    .join(", ");
                out.push_str(&format!(
                    "\n  {constant} = Fiddle::Function.new(LIBRARY[\"{}\"], [{types}], Fiddle::{})\n",
                    export.name,
                    ruby_type(signature.returns)
                ));
                let local = export.name.replace('-', "_");
                let names = signature
                    .parameters
                    .iter()
                    .map(|(name, _)| name.clone())
                    .collect::<Vec<_>>()
                    .join(", ");
                let values = signature
                    .parameters
                    .iter()
                    .map(|(name, _)| name.clone())
                    .collect::<Vec<_>>()
                    .join(", ");
                out.push_str(&format!(
                    "  def self.{local}({names})\n    {constant}.call({values})\n  end\n"
                ));
            }
            out.push_str("end\n");
            Ok(out)
        }
        other => Err(format!(
            "`{other}` is not a language this generator binds; it writes starters for {}",
            LANGUAGES.join(", ")
        )),
    }
}

/// Why a Ruby starter cannot carry an optional parameter: Fiddle has no struct-by-value call.
/// Ruby 起点为何承载不了可选参数：Fiddle 没有按值传结构体的调用形式。
fn optional_refused_in_ruby(export: &Export) -> String {
    format!(
        "`{}` takes an optional parameter; Fiddle passes scalars and pointers only, so the \
         `present`-flag struct has no spelling here — link the generated C header through a small \
         C bridge instead",
        export.name
    )
}

/// One export's parameters and return, refusing everything outside what a starter can carry.
/// 一个导出的参数与返回；起点承载不了的形状一律拒绝。
fn signature(export: &Export) -> Result<Signature, String> {
    export.validate_export()?;
    if !export.errors.is_empty() {
        return Err(format!(
            "`{}` declares typed errors; a status/out-parameter protocol needs a hand-written bridge, so this generator refuses it",
            export.name
        ));
    }
    let mut parameters = Vec::new();
    for (name, parameter) in &export.parameters {
        let carried = match parameter {
            ParameterType::Scalar(scalar) => BindingParameter::Scalar(*scalar),
            ParameterType::Optional(scalar) => BindingParameter::Optional(*scalar),
        };
        parameters.push((name.replace('-', "_"), carried));
    }
    Ok(Signature {
        parameters,
        returns: return_scalar(export)?,
    })
}

/// The return type, refusing everything outside the scalar subset.
/// 返回类型；标量子集之外一律拒绝。
fn return_scalar(export: &Export) -> Result<Scalar, String> {
    let returns = export
        .returns
        .as_ref()
        .ok_or_else(|| format!("`{}` declares no return type", export.name))?;
    match returns {
        ReturnType::Scalar(scalar) => Ok(*scalar),
        ReturnType::Text | ReturnType::Bytes => Err(format!(
            "`{}` returns text or bytes through a caller-owned buffer; that is a two-call protocol this generator refuses",
            export.name
        )),
        ReturnType::Optional(_) => Err(format!(
            "`{}` returns an optional value as a struct; this generator emits scalar bindings only",
            export.name
        )),
    }
}

/// The Go name of the optional struct one scalar needs.
/// 一个标量所需的可选结构体在 Go 里的名字。
fn go_optional(scalar: Scalar) -> String {
    format!("XirangOptional{}", class_name(scalar.token()))
}

/// `python` for `add`: the local name is the export name when it is a Python identifier.
/// `add` 的 `python` 名：导出名本身是 Python 标识符时就用它。
fn python_name(name: &str) -> String {
    name.replace('-', "_")
}

/// `Add` for `add`: Go wrappers are exported identifiers.
/// `add` 的 `Add`：Go 包装函数是导出标识符。
fn go_name(name: &str) -> String {
    let mut characters = name.chars();
    match characters.next() {
        Some(first) => first.to_uppercase().collect::<String>() + characters.as_str(),
        None => String::new(),
    }
}

/// The Go package name derived from the unit.
/// 由单元名推出的 Go 包名。
fn go_package(unit: &str) -> String {
    unit.replace('-', "_")
}

/// The class name stem: `widget` becomes `Widget`.
/// 类名前缀：`widget` 变成 `Widget`。
fn class_name(unit: &str) -> String {
    unit.split(['-', '_'])
        .map(|part| {
            let mut characters = part.chars();
            match characters.next() {
                Some(first) => first.to_uppercase().collect::<String>() + characters.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

fn python_type(scalar: Scalar) -> &'static str {
    match scalar {
        Scalar::I8 => "c_int8",
        Scalar::I16 => "c_int16",
        Scalar::I32 => "c_int32",
        Scalar::I64 => "c_int64",
        Scalar::U8 => "c_uint8",
        Scalar::U16 => "c_uint16",
        Scalar::U32 => "c_uint32",
        Scalar::U64 => "c_uint64",
        Scalar::F32 => "c_float",
        Scalar::F64 => "c_double",
        Scalar::Bool => "c_bool",
        Scalar::Utf8 | Scalar::Bytes => unreachable!("not a scalar the binding subset accepts"),
    }
}

